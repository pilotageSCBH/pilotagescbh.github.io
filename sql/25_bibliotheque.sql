-- un thème est-il partagé avec moi (lui ou un thème qui le contient) ?
create or replace function public.biblio_theme_partage(t bigint) returns boolean
language sql stable security definer set search_path = public as $$
  with recursive anc as (
    select id, parent_id, partage_tous from biblio_themes where id = t
    union
    select p.id, p.parent_id, p.partage_tous from biblio_themes p join anc on p.id = anc.parent_id
  )
  select exists (select 1 from anc where partage_tous and exists (select 1 from profils where id = auth.uid() and role <> 'lecture'))
      or exists (select 1 from anc join biblio_partages s on s.theme_id = anc.id where s.destinataire = auth.uid());
$$;
create or replace function public.biblio_theme_visible(t bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.est_actif() and (exists (select 1 from biblio_themes where id = t and proprietaire = auth.uid()) or public.biblio_theme_partage(t));
$$;
create or replace function public.biblio_livre_visible(l bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.est_actif() and exists (select 1 from biblio_livres b where b.id = l and (
    b.proprietaire = auth.uid()
    or (b.partage_tous and exists (select 1 from profils where id = auth.uid() and role <> 'lecture'))
    or exists (select 1 from biblio_partages s where s.livre_id = b.id and s.destinataire = auth.uid())
    or (b.theme_id is not null and public.biblio_theme_partage(b.theme_id))));
$$;
create or replace function public.biblio_a_moi(t bigint, l bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select case when t is not null then exists (select 1 from biblio_themes where id = t and proprietaire = auth.uid())
              else exists (select 1 from biblio_livres where id = l and proprietaire = auth.uid()) end;
$$;

-- contrôles : thème parent et thème d'un livre appartenant au même enseignant ; pas de thème dans lui-même
create or replace function public.biblio_controle_theme() returns trigger
language plpgsql security definer set search_path = public as $$
declare x bigint; n int := 0;
begin
  if new.parent_id is not null then
    if not exists (select 1 from biblio_themes where id = new.parent_id and proprietaire = new.proprietaire) then raise exception 'Thème parent introuvable.'; end if;
    x := new.parent_id;
    while x is not null and n < 100 loop
      if x = new.id then raise exception 'Un thème ne peut pas être rangé dans lui-même.'; end if;
      select parent_id into x from biblio_themes where id = x; n := n + 1;
    end loop;
  end if;
  return new;
end $$;
create or replace function public.biblio_controle_livre() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.theme_id is not null and not exists (select 1 from biblio_themes where id = new.theme_id and proprietaire = new.proprietaire) then
    raise exception 'Thème introuvable.';
  end if;
  return new;
end $$;
drop trigger if exists biblio_controle on public.biblio_themes;
create trigger biblio_controle before insert or update of parent_id on public.biblio_themes for each row execute function public.biblio_controle_theme();
drop trigger if exists biblio_controle on public.biblio_livres;
create trigger biblio_controle before insert or update of theme_id on public.biblio_livres for each row execute function public.biblio_controle_livre();

