-- =====================================================================================================
-- PILOTAGE BTS SCBH  ·  mise à jour 25 : MES RESSOURCES (« Ma bibliothèque » = La bibliothèque du bois, et « Mes cours »)
-- Chaque enseignant a sa bibliothèque personnelle : thèmes et sous-thèmes, ouvrages (titre, auteur, éditeur, année,
-- ISBN, pages, sommaire avec les numéros de page, couverture), fichiers rangés sur son Nuage.
-- Le site ne stocke aucun fichier : seulement les fiches, le chemin du fichier sur Nuage et de petites images
-- (couvertures et images des thèmes réduites). Un ouvrage ou un thème peut être partagé (en consultation) avec les
-- collègues choisis ou toute l'équipe.
-- Réglages Nuage de chaque enseignant : adresse du lien de partage de sa bibliothèque et de ses cours.
-- MES COURS : chaque document a un type (cours, exercice, TD/TP, évaluation, corrigé, ressource, autre), des étiquettes
-- et le chemin de son fichier sur Nuage.
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune saisie.)
-- =====================================================================================================

create table if not exists public.biblio_themes (
  id            bigint generated by default as identity primary key,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  parent_id     bigint references public.biblio_themes (id) on delete cascade,
  nom           text not null default '' check (length(nom) <= 200),
  dossier       text not null default '' check (length(dossier) <= 1000),   -- dossier correspondant sur Nuage
  image         text not null default '' check (length(image) <= 400000),  -- image de la tuile (réduite)
  ordre         integer not null default 0,
  partage_tous  boolean not null default false,
  cree_le       timestamptz not null default now(),
  maj_le        timestamptz not null default now()
);
create index if not exists biblio_themes_prop on public.biblio_themes (proprietaire);
create index if not exists biblio_themes_parent on public.biblio_themes (parent_id);

create table if not exists public.biblio_livres (
  id            bigint generated by default as identity primary key,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  theme_id      bigint references public.biblio_themes (id) on delete set null,   -- null = non classé
  titre         text not null default '' check (length(titre) <= 500),
  auteur        text not null default '' check (length(auteur) <= 300),
  editeur       text not null default '' check (length(editeur) <= 300),
  annee         text not null default '' check (length(annee) <= 20),
  isbn          text not null default '' check (length(isbn) <= 40),
  chemin        text not null default '' check (length(chemin) <= 1000),     -- fichier sur Nuage (depuis le dossier partagé)
  lien          text not null default '' check (length(lien) <= 1000),       -- lien direct (facultatif, prioritaire)
  pages         integer,
  sommaire      jsonb not null default '[]' check (jsonb_array_length(sommaire) <= 5000),   -- [{ t, p, n }]
  source        text not null default '',
  vignette      text not null default '' check (length(vignette) <= 200000),
  savoirs       text[] not null default '{}' check (cardinality(savoirs) <= 100),
  notes         text not null default '' check (length(notes) <= 5000),
  ordre         integer not null default 0,
  partage_tous  boolean not null default false,
  cree_le       timestamptz not null default now(),
  maj_le        timestamptz not null default now()
);
create index if not exists biblio_livres_prop on public.biblio_livres (proprietaire);
create index if not exists biblio_livres_theme on public.biblio_livres (theme_id);

create table if not exists public.biblio_partages (
  id            bigint generated by default as identity primary key,
  theme_id      bigint references public.biblio_themes (id) on delete cascade,
  livre_id      bigint references public.biblio_livres (id) on delete cascade,
  destinataire  uuid not null references public.profils (id) on delete cascade,
  check ((theme_id is null) <> (livre_id is null))
);
create unique index if not exists biblio_partages_theme on public.biblio_partages (theme_id, destinataire) where theme_id is not null;
create unique index if not exists biblio_partages_livre on public.biblio_partages (livre_id, destinataire) where livre_id is not null;
create index if not exists biblio_partages_dest on public.biblio_partages (destinataire);

-- réglages Nuage de chaque enseignant (liens de partage de ses dossiers « Bibliothèque » et « Mes cours »)
create table if not exists public.ressources_reglages (
