-- 1. séances réellement faites, par promotion (cochées par les enseignants de la matière)
create table if not exists public.seances_realisees (
  id            bigint generated by default as identity primary key,
  promotion_id  bigint not null references public.promotions (id) on delete cascade,
  seance_id     bigint not null references public.seances (id) on delete cascade,
  fait_le       date not null default current_date,
  par           uuid default auth.uid() references public.profils (id) on delete set null,
  unique (promotion_id, seance_id)
);
alter table public.seances_realisees enable row level security;
grant select, insert, update, delete on public.seances_realisees to authenticated;
grant usage on sequence public.seances_realisees_id_seq to authenticated;
drop policy if exists lecture on public.seances_realisees;
drop policy if exists ecriture on public.seances_realisees;
create policy lecture on public.seances_realisees for select to authenticated using (true);
-- écriture : enseignants de la matière de la séance (ou administrateur)
create policy ecriture on public.seances_realisees for all to authenticated
  using (public.est_redacteur() and public.peut_matiere((select s.matiere_id from public.seances x join public.sequences s on s.id = x.sequence_id where x.id = seance_id)))
  with check (public.est_redacteur() and public.peut_matiere((select s.matiere_id from public.seances x join public.sequences s on s.id = x.sequence_id where x.id = seance_id)));

-- 2. journal des sauvegardes téléchargées (pour le rappel hebdomadaire des administrateurs)
create table if not exists public.sauvegardes_faites (
  id     bigint generated by default as identity primary key,
  par    uuid default auth.uid() references public.profils (id) on delete set null,
  quand  timestamptz not null default now()
);
alter table public.sauvegardes_faites enable row level security;
grant select, insert on public.sauvegardes_faites to authenticated;
grant usage on sequence public.sauvegardes_faites_id_seq to authenticated;
drop policy if exists lecture on public.sauvegardes_faites;
drop policy if exists ajout on public.sauvegardes_faites;
create policy lecture on public.sauvegardes_faites for select to authenticated using (public.est_admin());
create policy ajout on public.sauvegardes_faites for insert to authenticated with check (public.est_admin() and par = auth.uid());

-- 3. les séances faites font partie de la sauvegarde complète
create or replace function public.tables_sauvegarde() returns text[] language sql immutable as $$
  select array['activites', 'taches', 'competences', 'savoirs', 'durees', 'matieres', 'enseignants', 'promotions', 'eleves',
               'sequences', 'seances', 'progression_semaines', 'progression_jours', 'progression_cases', 'couverture',
               'fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes', 'commentaires', 'evaluations', 'resultats', 'appreciations',
               'cours', 'cours_partages', 'ressources_reglages', 'biblio_themes', 'biblio_livres', 'biblio_partages',
               'comptes_eleves', 'publications_eleves', 'qcm', 'qcm_partages', 'qcm_dossiers_partages', 'qcm_sessions', 'qcm_reponses',
               'seances_realisees'];
$$;
