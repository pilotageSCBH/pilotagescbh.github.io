create extension if not exists pgcrypto with schema extensions;

-- comptes des élèves (un par élève ; un redoublant garde le sien)
create table if not exists public.comptes_eleves (
  eleve_id            bigint primary key references public.eleves (id) on delete cascade,
  identifiant         text not null unique check (identifiant ~ '^[a-z0-9][a-z0-9.\-]{2,59}$'),
  code_hash           text not null,
  doit_changer        boolean not null default true,
  actif               boolean not null default true,
  cree_le             timestamptz not null default now(),
  code_le             timestamptz not null default now(),
  derniere_connexion  timestamptz,
  echecs              integer not null default 0,
  bloque_jusqua       timestamptz
);
-- sessions ouvertes (seule l'empreinte du jeton est gardée)
create table if not exists public.sessions_eleves (
  jeton_hash  text primary key,
  eleve_id    bigint not null references public.comptes_eleves (eleve_id) on delete cascade,
  cree_le     timestamptz not null default now(),
  expire_le   timestamptz not null
);
create index if not exists sessions_eleves_eleve on public.sessions_eleves (eleve_id);
-- suivi des consultations (connexions, documents ouverts)
create table if not exists public.consultations_eleves (
  id        bigint generated by default as identity primary key,
  eleve_id  bigint not null references public.eleves (id) on delete cascade,
  quoi      text not null check (quoi in ('connexion', 'document', 'qcm')),
  livre_id  bigint,
  titre     text not null default '',
  quand     timestamptz not null default now()
);
create index if not exists consultations_eleves_eleve on public.consultations_eleves (eleve_id, quand desc);
-- documents de « Mes cours » publiés pour une promotion (un document ou tout un dossier)
create table if not exists public.publications_eleves (
  id            bigint generated by default as identity primary key,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  livre_id      bigint references public.biblio_livres (id) on delete cascade,
  theme_id      bigint references public.biblio_themes (id) on delete cascade,
  promotion_id  bigint not null references public.promotions (id) on delete cascade,
  a_partir_de   date,
  cree_le       timestamptz not null default now(),
  check ((livre_id is null) <> (theme_id is null))
);
create unique index if not exists publications_eleves_livre on public.publications_eleves (livre_id, promotion_id) where livre_id is not null;
create unique index if not exists publications_eleves_theme on public.publications_eleves (theme_id, promotion_id) where theme_id is not null;

-- droits : comptes et consultations lisibles par les enseignants (sans l'empreinte du code) ; écriture seulement par les fonctions
alter table public.comptes_eleves enable row level security;
alter table public.sessions_eleves enable row level security;
alter table public.consultations_eleves enable row level security;
alter table public.publications_eleves enable row level security;
revoke all on public.comptes_eleves, public.sessions_eleves, public.consultations_eleves, public.publications_eleves from anon, authenticated;
grant select (eleve_id, identifiant, doit_changer, actif, cree_le, code_le, derniere_connexion, bloque_jusqua) on public.comptes_eleves to authenticated;
grant select on public.consultations_eleves to authenticated;
grant select, insert, update, delete on public.publications_eleves to authenticated;
drop policy if exists lecture on public.comptes_eleves;
create policy lecture on public.comptes_eleves for select to authenticated using (public.est_redacteur());
-- vue lisible par les enseignants (sans l'empreinte du code)
create or replace view public.comptes_eleves_info with (security_invoker = true) as
  select eleve_id, identifiant, doit_changer, actif, cree_le, code_le, derniere_connexion, bloque_jusqua from public.comptes_eleves;
revoke all on public.comptes_eleves_info from anon;
grant select on public.comptes_eleves_info to authenticated;
drop policy if exists lecture on public.consultations_eleves;
create policy lecture on public.consultations_eleves for select to authenticated using (public.est_redacteur());
drop policy if exists lecture on public.publications_eleves;
drop policy if exists ecriture on public.publications_eleves;
create policy lecture on public.publications_eleves for select to authenticated using (public.est_actif());
create policy ecriture on public.publications_eleves for all to authenticated
  using (proprietaire = auth.uid() and public.est_redacteur())
  with check (proprietaire = auth.uid() and public.est_redacteur()
    and (livre_id is null or exists (select 1 from public.biblio_livres l where l.id = livre_id and l.proprietaire = auth.uid() and l.espace = 'cours'))
    and (theme_id is null or exists (select 1 from public.biblio_themes t where t.id = theme_id and t.proprietaire = auth.uid() and t.espace = 'cours')));

-- ------------------------------------------------------------------------------------------- outils
-- l'élève « actuel » d'un compte : un redoublant a une nouvelle fiche dans sa nouvelle promotion (origine_eleve_id)
create or replace function public.eleve_actuel(e bigint) returns bigint
language sql stable security definer set search_path = public as $$
  with recursive suite as (
    select id, promotion_id, 0 as n from eleves where id = e
    union all
    select x.id, x.promotion_id, s.n + 1 from eleves x join suite s on x.origine_eleve_id = s.id where s.n < 10)
  select s.id from suite s join promotions p on p.id = s.promotion_id order by p.annee_debut desc, s.n desc limit 1;
$$;
-- fin d'accès : un mois après la fin de la formation (30 juin de la 2e année)
create or replace function public.eleve_fin_acces(e bigint) returns date
language sql stable security definer set search_path = public as $$
  select make_date(p.annee_debut + 2, 7, 31) from eleves x join promotions p on p.id = x.promotion_id where x.id = public.eleve_actuel(e);
$$;
-- session valide → élève actuel ; sinon erreur
create or replace function public.eleve_de_session(jeton text, changement_ok boolean default false) returns bigint
language plpgsql security definer set search_path = public, extensions as $$
declare c record; e bigint;
begin
  select k.* into c from sessions_eleves s join comptes_eleves k on k.eleve_id = s.eleve_id
   where s.jeton_hash = encode(digest(coalesce(jeton, ''), 'sha256'), 'hex') and s.expire_le > now();
  if not found then raise exception 'Session expirée : reconnectez-vous.'; end if;
  if not c.actif then raise exception 'Votre compte est désactivé : voyez votre enseignant.'; end if;
  if public.eleve_fin_acces(c.eleve_id) < current_date then raise exception 'Votre accès a pris fin avec votre formation.'; end if;
  if c.doit_changer and not changement_ok then raise exception 'Choisissez d’abord votre propre code.'; end if;
  e := public.eleve_actuel(c.eleve_id);
  if exists (select 1 from eleves where id = e and coalesce(arret, '') <> '') then raise exception 'Votre accès est fermé : voyez votre enseignant.'; end if;
  return e;
end $$;

-- ------------------------------------------------------------------------------------------- administrateur
-- crée le compte (ou donne un nouveau code provisoire) ; le code est choisi par le site dans le navigateur de l'administrateur
create or replace function public.eleve_creer_compte(e bigint, ident text, code text) returns void
language plpgsql security definer set search_path = public, extensions as $$
begin
  if not public.est_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  if length(coalesce(code, '')) < 8 then raise exception 'Code provisoire trop court.'; end if;
  if exists (select 1 from comptes_eleves where identifiant = lower(ident) and eleve_id <> e) then raise exception 'Identifiant déjà utilisé : %', ident; end if;
  insert into comptes_eleves (eleve_id, identifiant, code_hash) values (e, lower(ident), crypt(code, gen_salt('bf', 8)))
  on conflict (eleve_id) do update set identifiant = excluded.identifiant, code_hash = excluded.code_hash, doit_changer = true, actif = true,
    echecs = 0, bloque_jusqua = null, code_le = now();
  delete from sessions_eleves where eleve_id = e;
end $$;
create or replace function public.eleve_activer_compte(e bigint, oui boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.est_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  update comptes_eleves set actif = oui, echecs = 0, bloque_jusqua = null where eleve_id = e;
  if not oui then delete from sessions_eleves where eleve_id = e; end if;
end $$;
create or replace function public.eleve_supprimer_compte(e bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.est_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  delete from comptes_eleves where eleve_id = e;
end $$;

-- ------------------------------------------------------------------------------------------- élève : connexion
create or replace function public.eleve_connexion(ident text, code text) returns json
language plpgsql security definer set search_path = public, extensions as $$
declare c record; j text; e bigint; x record;
begin
  delete from sessions_eleves where expire_le < now();
  select * into c from comptes_eleves where identifiant = lower(trim(coalesce(ident, '')));
  if not found then perform pg_sleep(0.4); return json_build_object('erreur', 'Identifiant ou code incorrect.'); end if;
  if c.bloque_jusqua is not null and c.bloque_jusqua > now() then
    raise exception 'Trop de codes faux : réessayez dans % minute(s).', ceil(extract(epoch from c.bloque_jusqua - now()) / 60)::int;
  end if;
  if c.code_hash <> crypt(coalesce(code, ''), c.code_hash) then
    -- 5 codes faux de suite : compte bloqué 15 minutes
    update comptes_eleves set echecs = case when echecs + 1 >= 5 then 0 else echecs + 1 end,
      bloque_jusqua = case when echecs + 1 >= 5 then now() + interval '15 minutes' else bloque_jusqua end where eleve_id = c.eleve_id;
    perform pg_sleep(0.4);
    -- pas d'exception ici : elle annulerait le comptage des codes faux
    return json_build_object('erreur', 'Identifiant ou code incorrect.');
  end if;
  if not c.actif then raise exception 'Votre compte est désactivé : voyez votre enseignant.'; end if;
  if public.eleve_fin_acces(c.eleve_id) < current_date then raise exception 'Votre accès a pris fin avec votre formation.'; end if;
  e := public.eleve_actuel(c.eleve_id);
  select x2.nom, x2.prenom, coalesce(x2.arret, '') as arret into x from eleves x2 where x2.id = e;
  if x.arret <> '' then raise exception 'Votre accès est fermé : voyez votre enseignant.'; end if;
  j := encode(gen_random_bytes(32), 'hex');
  insert into sessions_eleves (jeton_hash, eleve_id, expire_le) values (encode(digest(j, 'sha256'), 'hex'), c.eleve_id, now() + interval '30 days');
  update comptes_eleves set echecs = 0, bloque_jusqua = null, derniere_connexion = now() where eleve_id = c.eleve_id;
  insert into consultations_eleves (eleve_id, quoi) values (e, 'connexion');
  return json_build_object('jeton', j, 'doit_changer', c.doit_changer, 'nom', x.nom, 'prenom', x.prenom, 'identifiant', c.identifiant);
end $$;
create or replace function public.eleve_changer_code(jeton text, nouveau text) returns void
language plpgsql security definer set search_path = public, extensions as $$
declare e bigint; k bigint;
begin
  e := public.eleve_de_session(jeton, true);
  if length(coalesce(nouveau, '')) < 8 then raise exception 'Le code doit contenir au moins 8 caractères.'; end if;
  select s.eleve_id into k from sessions_eleves s where s.jeton_hash = encode(digest(jeton, 'sha256'), 'hex');
  update comptes_eleves set code_hash = crypt(nouveau, gen_salt('bf', 8)), doit_changer = false, code_le = now() where eleve_id = k;
  delete from sessions_eleves where eleve_id = k and jeton_hash <> encode(digest(jeton, 'sha256'), 'hex');
end $$;
create or replace function public.eleve_deconnexion(jeton text) returns void
language sql security definer set search_path = public, extensions as $$
  delete from sessions_eleves where jeton_hash = encode(digest(coalesce(jeton, ''), 'sha256'), 'hex');
$$;

-- ------------------------------------------------------------------------------------------- élève : ses données
-- documents publiés visibles par l'élève (publication d'un document, ou de tout un dossier et de ses sous-dossiers)
create or replace function public.eleve_livres_visibles(e bigint) returns table (livre_id bigint)
language sql stable security definer set search_path = public as $$
  with recursive p as (select promotion_id from eleves where id = e),
  pub as (select * from publications_eleves where promotion_id = (select promotion_id from p) and (a_partir_de is null or a_partir_de <= current_date)),
  arbre as (
    select t.id from biblio_themes t join pub on pub.theme_id = t.id where t.espace = 'cours'
    union
    select t.id from biblio_themes t join arbre a on t.parent_id = a.id)
  select l.id from biblio_livres l where l.espace = 'cours' and (l.id in (select pub.livre_id from pub) or l.theme_id in (select id from arbre));
$$;

create or replace function public.eleve_donnees(jeton text) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; c bigint; p bigint; r json;
begin
  e := public.eleve_de_session(jeton);
  select s.eleve_id into c from sessions_eleves s join comptes_eleves k on k.eleve_id = s.eleve_id
   where s.jeton_hash = encode(extensions.digest(jeton, 'sha256'), 'hex');
  select promotion_id into p from eleves where id = e;
  with seqs as (select * from sequences where promotion_id = p),
  seas as (select x.* from seances x join seqs s on s.id = x.sequence_id),
  ctr as (select * from contrats where promotion_id = p or sequence_id in (select id from seqs) or seance_id in (select id from seas)),
  crit as (select k.id, k.contrat_id, k.groupe, k.groupe_ordre, k.ordre, k.texte, k.coefficient from criteres k where k.actif and k.contrat_id in (select id from ctr)),
  livres as (select l.* from biblio_livres l where l.id in (select livre_id from public.eleve_livres_visibles(e))),
  themes as (
    with recursive t0 as (select t.* from biblio_themes t where t.id in (select theme_id from livres)
      union select t.* from biblio_themes t join t0 on t.id = t0.parent_id)
    select distinct id, parent_id, nom, ordre, proprietaire from t0)
  select json_build_object(
    'eleve', (select json_build_object('id', x.id, 'nom', x.nom, 'prenom', x.prenom, 'statut', x.statut, 'promotion_id', x.promotion_id, 'redoublant', x.redoublant) from eleves x where x.id = e),
    'compte', (select json_build_object('identifiant', k.identifiant, 'fin_acces', public.eleve_fin_acces(k.eleve_id)) from comptes_eleves k where k.eleve_id = c),
    'promotions', (select json_agg(row_to_json(x)) from promotions x where x.id = p),
    'matieres', (select coalesce(json_agg(row_to_json(m) order by m.ordre), '[]') from matieres m),
    'enseignants', (select coalesce(json_agg(json_build_object('id', x.id, 'nom', x.nom, 'matieres', x.matieres, 'profil_id', x.profil_id) order by x.ordre), '[]') from enseignants x),
    'competences', (select coalesce(json_agg(json_build_object('code', x.code, 'libelle', x.libelle, 'libelle_court', x.libelle_court, 'ordre', x.ordre) order by x.ordre), '[]') from competences x),
    'savoirs', (select coalesce(json_agg(json_build_object('code', x.code, 'libelle', x.libelle, 'libelle_court', x.libelle_court, 'ordre', x.ordre) order by x.ordre), '[]') from savoirs x),
    'sequences', (select coalesce(json_agg(json_build_object('id', s.id, 'matiere_id', s.matiere_id, 'numero', s.numero, 'intitule', s.intitule, 'objectif', s.objectif, 'promotion_id', s.promotion_id) order by s.matiere_id, s.numero), '[]') from seqs s),
    'seances', (select coalesce(json_agg(json_build_object('id', x.id, 'sequence_id', x.sequence_id, 'numero', x.numero, 'titre', x.titre, 'duree', x.duree, 'objectif_inter', x.objectif_inter,
        'savoirs', x.savoirs, 'competences', x.competences, 'cours_lies', (select coalesce(json_agg(json_build_object('id', (cl ->> 'id')::bigint, 'titre', cl ->> 'titre')), '[]')
          from jsonb_array_elements(coalesce(x.cours_lies, '[]')) cl where (cl ->> 'id') ~ '^\d+$' and (cl ->> 'id')::bigint in (select id from livres)))
        order by x.sequence_id, x.numero), '[]') from seas x),
    'progression_semaines', (select coalesce(json_agg(row_to_json(x)), '[]') from progression_semaines x where x.promotion_id = p),
    'progression_jours', (select coalesce(json_agg(row_to_json(x)), '[]') from progression_jours x where x.promotion_id = p),
    'progression_cases', (select coalesce(json_agg(json_build_object('promotion_id', x.promotion_id, 'matiere_id', x.matiere_id, 'semaine', x.semaine, 'seance_id', x.seance_id, 'seance2_id', x.seance2_id, 'texte', x.texte)), '[]') from progression_cases x where x.promotion_id = p),
    'contrats', (select coalesce(json_agg(json_build_object('id', x.id, 'type', x.type, 'sequence_id', x.sequence_id, 'seance_id', x.seance_id, 'date_eval', x.date_eval, 'forme', x.forme,
        'lieu', x.lieu, 'duree', x.duree, 'titre', x.titre, 'matiere_id', x.matiere_id, 'promotion_id', x.promotion_id, 'coef_resultat', x.coef_resultat)), '[]') from ctr x),
    'criteres', (select coalesce(json_agg(row_to_json(k)), '[]') from crit k),
    'notes', (select coalesce(json_agg(json_build_object('critere_id', n.critere_id, 'eleve_id', n.eleve_id, 'valeur', n.valeur)), '[]') from notes n where n.eleve_id = e and n.critere_id in (select id from crit)),
    'evaluations', (select coalesce(json_agg(json_build_object('id', v.id, 'matiere_id', v.matiere_id, 'libelle', v.libelle, 'date_eval', v.date_eval, 'coefficient', v.coefficient, 'bareme', v.bareme, 'promotion_id', v.promotion_id)), '[]') from evaluations v where v.promotion_id = p),
    'resultats', (select coalesce(json_agg(row_to_json(x)), '[]') from resultats x where x.eleve_id = e),
    'appreciations', (select coalesce(json_agg(json_build_object('matiere_id', a.matiere_id, 'texte', a.texte)), '[]') from appreciations a where a.eleve_id = e),
    'documents', (select coalesce(json_agg(json_build_object('id', l.id, 'titre', l.titre, 'genre', l.genre, 'theme_id', l.theme_id, 'sommaire', l.sommaire, 'savoirs', l.savoirs,
        'pages', l.pages, 'vignette', l.vignette, 'ordre', l.ordre, 'extension', lower(substring(coalesce(nullif(l.chemin, ''), l.lien) from '\.([A-Za-z0-9]{1,5})$')),
        'fichier', (l.chemin <> '' or l.lien <> ''), 'auteur', (select nom from profils where id = l.proprietaire)) order by l.ordre, l.titre), '[]') from livres l),
    'dossiers', (select coalesce(json_agg(json_build_object('id', t.id, 'parent_id', t.parent_id, 'nom', t.nom, 'ordre', t.ordre)), '[]') from themes t)
  ) into r;
  return r;
end $$;

-- un document publié : où le trouver sur Nuage (pour le relais « nuage » ; jamais montré à l'élève)
create or replace function public.eleve_document(jeton text, livre bigint) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; l record; g record;
begin
  e := public.eleve_de_session(jeton);
  if livre not in (select livre_id from public.eleve_livres_visibles(e)) then raise exception 'Document non publié pour votre promotion.'; end if;
  select * into l from biblio_livres where id = livre;
  select * into g from ressources_reglages where proprietaire = l.proprietaire;
  insert into consultations_eleves (eleve_id, quoi, livre_id, titre) values (e, 'document', l.id, left(l.titre, 200));
  return json_build_object('lien', coalesce(g.lien_cours, ''), 'chemin', l.chemin, 'lien_direct', l.lien, 'titre', l.titre);
end $$;

revoke all on function public.eleve_actuel(bigint), public.eleve_fin_acces(bigint), public.eleve_de_session(text, boolean), public.eleve_livres_visibles(bigint) from public, anon, authenticated;
grant execute on function public.eleve_connexion(text, text), public.eleve_changer_code(text, text), public.eleve_deconnexion(text),
  public.eleve_donnees(text), public.eleve_document(text, bigint) to anon, authenticated;
grant execute on function public.eleve_creer_compte(bigint, text, text), public.eleve_activer_compte(bigint, boolean), public.eleve_supprimer_compte(bigint) to authenticated;
grant execute on function public.eleve_fin_acces(bigint) to authenticated;

