-- Chaque élève a un compte (identifiant + code) créé par l'administrateur, valable jusqu'à un mois après la fin de sa
-- formation (redoublement compris). Les élèves n'utilisent pas les comptes enseignants : ils se connectent par des
-- fonctions dédiées qui ne renvoient QUE leurs propres données (leur semaine, leur formation, leurs résultats, les
-- documents publiés pour leur promotion). Les codes ne sont jamais gardés en clair (empreinte bcrypt).
-- Après 5 codes faux, le compte est bloqué 15 minutes.
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune saisie.)
