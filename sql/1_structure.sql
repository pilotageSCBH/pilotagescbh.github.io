create extension if not exists pgcrypto with schema extensions;

-- ----------------------------------------------------------------------------------------------- comptes
-- profil d'un utilisateur connecté (créé automatiquement à sa première connexion)
create table if not exists public.profils (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text not null unique,
  nom         text not null default '',
  role        text not null default 'enseignant' check (role in ('admin', 'enseignant')),
  actif       boolean not null default true,
  cree_le     timestamptz not null default now()
);

-- comptes autorisés par l'administrateur, en attente de leur première connexion
create table if not exists public.invitations (
  email       text primary key check (email = lower(email)),
  nom         text not null default '',
  role        text not null default 'enseignant' check (role in ('admin', 'enseignant')),
  enseignant_id bigint,
  cree_le     timestamptz not null default now()
);

-- ----------------------------------------------------------------------------------------------- promotion
create table if not exists public.promotion (
  id          int primary key default 1 check (id = 1),           -- une seule ligne
  libelle     text not null default '2026-2028',
  annee_debut int  not null default 2026,
  etablissement text not null default '',
  maj_le      timestamptz not null default now(),
  maj_par     uuid default auth.uid()
);
insert into public.promotion (id) values (1) on conflict do nothing;

create table if not exists public.matieres (
  id          bigint generated by default as identity primary key,
  ordre       int  not null default 0,
  nom         text not null,
  abreviation text not null default '',
  couleur     text not null default '#1E8F86'
);

create table if not exists public.enseignants (
  id          bigint generated by default as identity primary key,
  nom         text not null,
  profil_id   uuid references public.profils (id) on delete set null,
  matieres    bigint[] not null default '{}',                     -- matières enseignées (id)
  ordre       int not null default 0
);

-- ----------------------------------------------------------------------------------------------- élèves
create table if not exists public.eleves (
  id                bigint generated by default as identity primary key,
  nom               text not null default '',
  prenom            text not null default '',
  naissance         date,
  statut            text not null default 'Scolaire' check (statut in ('Scolaire', 'Apprenti')),
  telephone         text not null default '',
  mail              text not null default '',
  commune           text not null default '',
  code_postal       text not null default '',
  departement       text not null default '',
  entreprise        text not null default '',
  entreprise_commune text not null default '',
  entreprise_cp     text not null default '',
  etudes            text not null default '',
  etablissement     text not null default '',
  projet            text not null default '',
  arret             text not null default '',                       -- vide = en formation
  maj_le            timestamptz not null default now(),
  maj_par           uuid default auth.uid()
);

-- ----------------------------------------------------------------------------------------------- référentiel
create table if not exists public.activites (
  code    text primary key,
  libelle text not null,
  ordre   int not null default 0
);
create table if not exists public.taches (
  code       text primary key,
  activite   text references public.activites (code) on update cascade,
  libelle    text not null,
  resultats  text[] not null default '{}',                         -- résultats attendus
  ordre      int not null default 0
);
create table if not exists public.competences (
  code            text primary key,
  libelle         text not null,
  libelle_court   text not null default '',
  famille         text not null default '',
  famille_libelle text not null default '',
  type            text not null default '',
  indicateurs     text[] not null default '{}',                    -- indicateurs de performance
  ordre           int not null default 0
);
create table if not exists public.savoirs (
  code          text primary key,
  libelle       text not null,
  libelle_court text not null default '',
  taxonomie     int,
  ordre         int not null default 0
);
create table if not exists public.durees (
  heures numeric primary key
);

-- ----------------------------------------------------------------------------------------------- séquençages
create table if not exists public.sequences (
  id          bigint generated by default as identity primary key,
  matiere_id  bigint not null references public.matieres (id) on delete cascade,
  numero      int not null,
  intitule    text not null default '',
  objectif    text not null default '',
  maj_le      timestamptz not null default now(),
  maj_par     uuid default auth.uid(),
  constraint sequences_num unique (matiere_id, numero) deferrable initially deferred
);
create table if not exists public.seances (
  id              bigint generated by default as identity primary key,
  sequence_id     bigint not null references public.sequences (id) on delete cascade,
  numero          int not null,
  titre           text not null default '',
  duree           numeric,
  objectif_inter  text not null default '',                        -- objectif intermédiaire
  objectifs_ops   text not null default '',                        -- objectifs opérationnels (une ligne par objectif)
  cours           text not null default '',                        -- cours mobilisés
  competences     text[] not null default '{}',                    -- codes compétences
  savoirs         text[] not null default '{}',                    -- codes savoirs
  maj_le          timestamptz not null default now(),
  maj_par         uuid default auth.uid(),
  constraint seances_num unique (sequence_id, numero) deferrable initially deferred
);
create index if not exists seances_sequence on public.seances (sequence_id);
create index if not exists sequences_matiere on public.sequences (matiere_id);

-- ----------------------------------------------------------------------------------------------- traçabilité
create or replace function public.trace_maj() returns trigger language plpgsql as $$
begin
  new.maj_le := now();
  new.maj_par := auth.uid();
  return new;
end $$;
do $$ declare t text; begin
  foreach t in array array['promotion', 'eleves', 'sequences', 'seances'] loop
    execute format('drop trigger if exists trace_maj on public.%I', t);
    execute format('create trigger trace_maj before update on public.%I for each row execute function public.trace_maj()', t);
  end loop;
end $$;

-- ----------------------------------------------------------------------------------------------- droits
-- utilisateur connecté, compte actif ?
create or replace function public.est_actif() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profils where id = auth.uid() and actif);
$$;
create or replace function public.est_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profils where id = auth.uid() and actif and role = 'admin');
$$;
-- peut modifier la matière m : administrateur, ou enseignant de cette matière
create or replace function public.peut_matiere(m bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.est_admin() or exists (
    select 1 from enseignants e join profils p on p.id = e.profil_id
    where p.id = auth.uid() and p.actif and m = any (e.matieres));
$$;
create or replace function public.peut_sequence(s bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.peut_matiere((select matiere_id from sequences where id = s));
$$;

do $$ declare t text; begin
  foreach t in array array['profils', 'invitations', 'promotion', 'matieres', 'enseignants', 'eleves', 'activites',
                           'taches', 'competences', 'savoirs', 'durees', 'sequences', 'seances'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists lecture on public.%I', t);
    execute format('drop policy if exists ecriture on public.%I', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- lecture : tout compte actif lit tout (sauf comptes et invitations : administrateur, ou son propre profil)
do $$ declare t text; begin
  foreach t in array array['promotion', 'matieres', 'enseignants', 'eleves', 'activites', 'taches', 'competences',
                           'savoirs', 'durees', 'sequences', 'seances'] loop
    execute format('create policy lecture on public.%I for select to authenticated using (public.est_actif())', t);
  end loop;
end $$;
create policy lecture on public.profils for select to authenticated using (id = auth.uid() or public.est_admin());
create policy lecture on public.invitations for select to authenticated using (public.est_admin());

-- écriture : administrateur (promotion, matières, équipe, élèves, référentiel, comptes)
do $$ declare t text; begin
  foreach t in array array['profils', 'invitations', 'promotion', 'matieres', 'enseignants', 'eleves', 'activites',
                           'taches', 'competences', 'savoirs', 'durees'] loop
    execute format('create policy ecriture on public.%I for all to authenticated using (public.est_admin()) with check (public.est_admin())', t);
  end loop;
end $$;
-- séquençages : administrateur, ou enseignant de la matière
create policy ecriture on public.sequences for all to authenticated
  using (public.peut_matiere(matiere_id)) with check (public.peut_matiere(matiere_id));
create policy ecriture on public.seances for all to authenticated
  using (public.peut_sequence(sequence_id)) with check (public.peut_sequence(sequence_id));

-- ----------------------------------------------------------------------------------------------- 1re connexion
-- Un compte ne peut être créé que si l'administrateur l'a autorisé (table invitations).
-- Exception : le tout premier compte créé devient administrateur.
create or replace function public.nouveau_compte() returns trigger
language plpgsql security definer set search_path = public as $$
declare inv invitations%rowtype; premier boolean;
begin
  premier := not exists (select 1 from profils);
  select * into inv from invitations where email = lower(new.email);
  if not premier and inv.email is null then
    raise exception 'Compte non autorisé : demandez à l''administrateur de vous ajouter.';
  end if;
  insert into profils (id, email, nom, role)
  values (new.id, lower(new.email), coalesce(inv.nom, ''), case when premier then 'admin' else inv.role end);
  if inv.enseignant_id is not null then
    update enseignants set profil_id = new.id where id = inv.enseignant_id;
  end if;
  delete from invitations where email = lower(new.email);
  return new;
end $$;
drop trigger if exists nouveau_compte on auth.users;
create trigger nouveau_compte after insert on auth.users for each row execute function public.nouveau_compte();

-- l'administrateur choisit un nouveau code pour un collègue (code oublié)
create or replace function public.admin_nouveau_code(compte uuid, code text) returns void
language plpgsql security definer set search_path = public, extensions as $$
begin
  if not public.est_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  if length(code) < 6 then raise exception 'Le code doit faire au moins 6 caractères.'; end if;
  update auth.users set encrypted_password = extensions.crypt(code, extensions.gen_salt('bf')) where id = compte;
end $$;

-- un enseignant connecté peut-il ouvrir l'application ? (compte présent et actif)
create or replace function public.mon_profil() returns json
language sql stable security definer set search_path = public as $$
  select row_to_json(p) from (
    select pr.id, pr.email, pr.nom, pr.role, pr.actif,
           coalesce((select array_agg(m order by m) from enseignants e, unnest(e.matieres) m where e.profil_id = pr.id), '{}') as matieres
    from profils pr where pr.id = auth.uid()) p;
$$;

-- ----------------------------------------------------------------------------------------------- séquençage : opérations
-- (droits vérifiés par les règles ci-dessus : fonctions exécutées avec les droits de l'utilisateur)
create or replace function public.ajouter_sequence(m bigint) returns bigint
language plpgsql as $$
declare n int; s bigint;
begin
  if not public.peut_matiere(m) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  select coalesce(max(numero), 0) + 1 into n from sequences where matiere_id = m;
  if n > 10 then raise exception '10 séquences au maximum par matière.'; end if;
  insert into sequences (matiere_id, numero) values (m, n) returning id into s;
  insert into seances (sequence_id, numero) values (s, 1);
  return s;
end $$;

create or replace function public.supprimer_sequence(s bigint) returns void
language plpgsql as $$
declare m bigint; n int;
begin
  select matiere_id, numero into m, n from sequences where id = s;
  if m is null then raise exception 'Séquence introuvable.'; end if;
  if not public.peut_matiere(m) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  delete from sequences where id = s;
  update sequences set numero = numero - 1 where matiere_id = m and numero > n;
end $$;

create or replace function public.inserer_seance(s bigint, apres int) returns bigint
language plpgsql as $$
declare r bigint;
begin
  if not public.peut_sequence(s) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  update seances set numero = numero + 1 where sequence_id = s and numero > apres;
  insert into seances (sequence_id, numero) values (s, apres + 1) returning id into r;
  return r;
end $$;

create or replace function public.supprimer_seance(x bigint) returns void
language plpgsql as $$
declare s bigint; n int;
begin
  select sequence_id, numero into s, n from seances where id = x;
  if s is null then raise exception 'Séance introuvable.'; end if;
  if not public.peut_sequence(s) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  if (select count(*) from seances where sequence_id = s) <= 1 then
    raise exception 'Une séquence doit garder au moins une séance.';
  end if;
  delete from seances where id = x;
  update seances set numero = numero - 1 where sequence_id = s and numero > n;
end $$;

-- déplace une séance à une autre place dans sa séquence (glisser-déposer) ; les autres se décalent
create or replace function public.deplacer_seance(x bigint, nouveau int) returns void
language plpgsql as $$
declare s bigint; n int; nb int;
begin
  select sequence_id, numero into s, n from seances where id = x;
  if s is null then raise exception 'Séance introuvable.'; end if;
  if not public.peut_sequence(s) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  select count(*) into nb from seances where sequence_id = s;
  nouveau := greatest(1, least(nouveau, nb));
  if nouveau = n then return; end if;
  if nouveau < n then
    update seances set numero = numero + 1 where sequence_id = s and numero >= nouveau and numero < n;
  else
    update seances set numero = numero - 1 where sequence_id = s and numero > n and numero <= nouveau;
  end if;
  update seances set numero = nouveau where id = x;
end $$;

