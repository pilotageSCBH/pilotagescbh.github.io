-- =====================================================================================================
-- PILOTAGE BTS SCBH  ·  mise à jour 23 : MES COURS RESSOURCES (espace personnel de chaque enseignant)
-- Chaque enseignant range ses cours dans une arborescence de dossiers, avec pour chaque cours son sommaire
-- détaillé, les savoirs associés du référentiel, des mots-clés et un lien (Nuage…).
-- Tout est privé par défaut ; un dossier ou un cours peut être partagé (en consultation) avec les collègues
-- de son choix ou avec toute l'équipe. Le partage d'un dossier comprend tout son contenu.
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune saisie.)
-- =====================================================================================================

create table if not exists public.cours (
  id            bigint generated by default as identity primary key,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  parent_id     bigint references public.cours (id) on delete cascade,      -- dossier qui le contient (null = racine)
  type          text not null default 'cours' check (type in ('dossier', 'cours')),
  titre         text not null default '',
  sommaire      text not null default '',       -- une ligne par titre ; 2 espaces de retrait par niveau
  savoirs       text[] not null default '{}',   -- codes des savoirs associés (S11-1…)
  mots_cles     text not null default '',
  lien          text not null default '',
  partage_tous  boolean not null default false, -- partagé avec toute l'équipe
  ordre         integer not null default 0,
  cree_le       timestamptz not null default now(),
  maj_le        timestamptz not null default now()
);
create index if not exists cours_proprietaire on public.cours (proprietaire);
create index if not exists cours_parent on public.cours (parent_id);

create table if not exists public.cours_partages (
  cours_id      bigint not null references public.cours (id) on delete cascade,
  destinataire  uuid not null references public.profils (id) on delete cascade,
  primary key (cours_id, destinataire)
);
create index if not exists cours_partages_dest on public.cours_partages (destinataire);

-- date de dernière modification
create or replace function public.cours_maj() returns trigger language plpgsql as $$
begin new.maj_le := now(); return new; end $$;
drop trigger if exists cours_maj on public.cours;
create trigger cours_maj before update on public.cours for each row execute function public.cours_maj();

-- un élément appartient-il à l'utilisateur connecté ?
create or replace function public.cours_a_moi(c bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from cours where id = c and proprietaire = auth.uid());
$$;

-- un élément est-il visible : à moi, ou partagé (lui-même ou un dossier qui le contient) avec moi ou avec tous
create or replace function public.cours_visible(c bigint) returns boolean
language sql stable security definer set search_path = public as $$
  with recursive anc as (
    select id, parent_id, proprietaire, partage_tous from cours where id = c
    union
    select p.id, p.parent_id, p.proprietaire, p.partage_tous from cours p join anc on p.id = anc.parent_id
  )
  select public.est_actif() and (
    exists (select 1 from anc where proprietaire = auth.uid())
    or exists (select 1 from anc where partage_tous and exists (select 1 from profils where id = auth.uid() and role <> 'lecture'))
    or exists (select 1 from anc join cours_partages s on s.cours_id = anc.id where s.destinataire = auth.uid()));
$$;

-- contrôles : le dossier parent est un de mes dossiers, et un dossier ne peut pas entrer dans lui-même
create or replace function public.cours_controle() returns trigger
language plpgsql security definer set search_path = public as $$
declare x bigint; n int := 0;
begin
  if new.parent_id is not null then
    if not exists (select 1 from cours where id = new.parent_id and type = 'dossier' and proprietaire = new.proprietaire) then
      raise exception 'Dossier de destination introuvable.';
    end if;
    x := new.parent_id;
    while x is not null and n < 100 loop
      if x = new.id then raise exception 'Un dossier ne peut pas être déplacé dans lui-même.'; end if;
      select parent_id into x from cours where id = x; n := n + 1;
    end loop;
  end if;
  return new;
end $$;
drop trigger if exists cours_controle on public.cours;
create trigger cours_controle before insert or update of parent_id on public.cours for each row execute function public.cours_controle();

alter table public.cours enable row level security;
alter table public.cours_partages enable row level security;
revoke all on public.cours, public.cours_partages from anon;
grant select, insert, update, delete on public.cours, public.cours_partages to authenticated;

drop policy if exists lecture on public.cours;
drop policy if exists ecriture on public.cours;
create policy lecture on public.cours for select to authenticated using (public.cours_visible(id));
create policy ecriture on public.cours for all to authenticated
  using (proprietaire = auth.uid() and public.est_redacteur())
  with check (proprietaire = auth.uid() and public.est_redacteur());

drop policy if exists lecture on public.cours_partages;
drop policy if exists ecriture on public.cours_partages;
create policy lecture on public.cours_partages for select to authenticated
  using (destinataire = auth.uid() or public.cours_a_moi(cours_id));
create policy ecriture on public.cours_partages for all to authenticated
  using (public.cours_a_moi(cours_id) and public.est_redacteur())
  with check (public.cours_a_moi(cours_id) and public.est_redacteur());

-- noms des collègues (pour le partage et pour savoir de qui vient un cours partagé)
create or replace function public.collegues() returns table (id uuid, nom text)
language sql stable security definer set search_path = public as $$
  select p.id, coalesce(nullif((select e.nom from enseignants e where e.profil_id = p.id order by e.id limit 1), ''), nullif(p.nom, ''), split_part(p.email, '@', 1))
  from profils p
  where p.actif and p.role <> 'lecture' and public.est_actif()
  order by 2;
$$;

-- la sauvegarde complète (Administration) comprend aussi les cours ressources et leurs partages
create or replace function public.tables_sauvegarde() returns text[] language sql immutable as $$
  select array['activites', 'taches', 'competences', 'savoirs', 'durees', 'matieres', 'enseignants', 'promotions', 'eleves',
               'sequences', 'seances', 'progression_semaines', 'progression_jours', 'progression_cases', 'couverture',
               'fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes', 'commentaires', 'evaluations', 'resultats', 'appreciations', 'cours', 'cours_partages'];
$$;

create or replace function public.restaurer(d jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare t text; lignes jsonb; cols text; nb int; bilan jsonb := '{}'; tabs text[] := public.tables_sauvegarde(); i int;
begin
  if not public.est_admin() then raise exception 'Réservé à l''administrateur.'; end if;
  if d ->> 'format' is distinct from 'pilotage-scbh-sauvegarde' then raise exception 'Ce fichier n''est pas une sauvegarde du site.'; end if;
  if jsonb_typeof(d -> 'tables') <> 'object' or not (d -> 'tables') ? 'promotions' then raise exception 'Sauvegarde incomplète.'; end if;
  set constraints all deferred;
  -- pas d'historique ni de traces automatiques pendant la restauration
  foreach t in array tabs loop
    if to_regclass('public.' || t) is not null then execute format('alter table public.%I disable trigger user', t); end if;
  end loop;
  -- suppression (enfants d'abord)
  for i in reverse cardinality(tabs) .. 1 loop
    t := tabs[i];
    if to_regclass('public.' || t) is not null then execute format('delete from public.%I', t); end if;
  end loop;
  -- comptes : on ne relie que les comptes qui existent encore
  d := jsonb_set(d, '{tables,enseignants}', coalesce((select jsonb_agg(case when e ->> 'profil_id' is not null
      and not exists (select 1 from profils where id = (e ->> 'profil_id')::uuid) then jsonb_set(e, '{profil_id}', 'null') else e end)
      from jsonb_array_elements(d -> 'tables' -> 'enseignants') e), '[]'));
  d := jsonb_set(d, '{tables,commentaires}', coalesce((select jsonb_agg(e) from jsonb_array_elements(coalesce(d -> 'tables' -> 'commentaires', '[]')) e
      where exists (select 1 from profils where id = (e ->> 'auteur')::uuid)), '[]'));
  -- cours ressources : seulement ceux des comptes qui existent encore
  if d -> 'tables' ? 'cours' then
    d := jsonb_set(d, '{tables,cours}', coalesce((select jsonb_agg(e) from jsonb_array_elements(d -> 'tables' -> 'cours') e
        where exists (select 1 from profils where id = (e ->> 'proprietaire')::uuid)), '[]'));
    d := jsonb_set(d, '{tables,cours}', coalesce((select jsonb_agg(case when e ->> 'parent_id' is not null and not exists (select 1 from jsonb_array_elements(d -> 'tables' -> 'cours') x where x ->> 'id' = e ->> 'parent_id')
        then jsonb_set(e, '{parent_id}', 'null') else e end) from jsonb_array_elements(d -> 'tables' -> 'cours') e), '[]'));
  end if;
  if d -> 'tables' ? 'cours_partages' then
    d := jsonb_set(d, '{tables,cours_partages}', coalesce((select jsonb_agg(e) from jsonb_array_elements(d -> 'tables' -> 'cours_partages') e
        where exists (select 1 from profils where id = (e ->> 'destinataire')::uuid)
          and exists (select 1 from jsonb_array_elements(d -> 'tables' -> 'cours') x where x ->> 'id' = e ->> 'cours_id')), '[]'));
  end if;
  -- insertion (parents d'abord), colonnes présentes à la fois dans le fichier et dans la table
  foreach t in array tabs loop
    lignes := d -> 'tables' -> t;
    if to_regclass('public.' || t) is null or lignes is null or jsonb_array_length(lignes) = 0 then continue; end if;
    select string_agg(quote_ident(a.attname), ', ') into cols
    from pg_attribute a where a.attrelid = ('public.' || t)::regclass and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
      and exists (select 1 from jsonb_array_elements(lignes) e where e ? a.attname);
    execute format('insert into public.%I (%s) select %s from jsonb_populate_recordset(null::public.%I, $1)', t, cols, cols, t) using lignes;
    get diagnostics nb = row_count;
    bilan := bilan || jsonb_build_object(t, nb);
    if exists (select 1 from pg_attribute where attrelid = ('public.' || t)::regclass and attname = 'id' and attnum > 0)
       and pg_get_serial_sequence('public.' || t, 'id') is not null then
      execute format('select setval(pg_get_serial_sequence(''public.%I'', ''id''), greatest(coalesce((select max(id) from public.%I), 0), 1))', t, t);
    end if;
  end loop;
  foreach t in array tabs loop
    if to_regclass('public.' || t) is not null then execute format('alter table public.%I enable trigger user', t); end if;
  end loop;
  -- l'historique d'avant la restauration ne correspond plus aux données : il est vidé
  delete from journal;
  return bilan;
end $$;

