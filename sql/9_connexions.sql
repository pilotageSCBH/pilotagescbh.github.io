create table if not exists public.connexions (
  id                bigint generated by default as identity primary key,
  profil_id         uuid not null references public.profils (id) on delete cascade,
  debut             timestamptz not null default now(),
  derniere_activite timestamptz not null default now()
);
create index if not exists connexions_profil on public.connexions (profil_id, debut desc);
alter table public.connexions enable row level security;
revoke all on public.connexions from anon, authenticated;
grant select on public.connexions to authenticated;
drop policy if exists lecture on public.connexions;
create policy lecture on public.connexions for select to authenticated using (public.est_admin());

-- signal de présence : prolonge la connexion c si elle est récente, sinon en ouvre une nouvelle ; renvoie son numéro
create or replace function public.presence(c bigint) returns bigint
language plpgsql security definer set search_path = public as $$
declare r bigint;
begin
  if not public.est_actif() then return null; end if;
  update connexions set derniere_activite = now()
  where id = c and profil_id = auth.uid() and derniere_activite > now() - interval '30 minutes'
  returning id into r;
  if r is null then
    insert into connexions (profil_id) values (auth.uid()) returning id into r;
  end if;
  return r;
end $$;

-- bilan par compte depuis une date : nombre de connexions, temps total (secondes), dernière activité
create or replace function public.bilan_connexions(depuis timestamptz) returns table (profil_id uuid, nb bigint, secondes bigint, derniere timestamptz)
language sql stable security definer set search_path = public as $$
  select p.id, count(c.id), coalesce(sum(extract(epoch from c.derniere_activite - c.debut))::bigint, 0),
         (select max(derniere_activite) from connexions x where x.profil_id = p.id)
  from profils p left join connexions c on c.profil_id = p.id and c.debut >= depuis
  where public.est_admin()
  group by p.id;
$$;

revoke execute on all functions in schema public from anon, public;
grant execute on all functions in schema public to authenticated;
