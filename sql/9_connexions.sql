-- Une « connexion » = une période d'utilisation : elle se prolonge tant que l'application est ouverte et utilisée
-- (signal toutes les minutes) ; après 30 minutes sans activité, la suivante compte comme une nouvelle connexion.
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune donnée.)
