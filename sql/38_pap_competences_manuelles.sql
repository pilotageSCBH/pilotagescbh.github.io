-- =====================================================================================================
-- 38 · Élèves : PAP (plan d'accompagnement personnalisé) ; compétences évaluées sans fiche contrat (ex. en entreprise)
-- À exécuter après le script 37. Peut être exécuté plusieurs fois sans risque.
-- Aucune donnée d'élève dans ce script (seulement la structure).
-- Le PAP n'est visible que des enseignants : il n'est jamais envoyé dans l'espace élève.
-- =====================================================================================================

-- 1. PAP sur la fiche de l'élève (modifiable, comme le reste de la fiche, par l'administrateur)
alter table public.eleves add column if not exists pap boolean not null default false;
alter table public.eleves add column if not exists pap_amenagements text not null default '' check (length(pap_amenagements) <= 4000);

-- 2. compétences évaluées directement dans la validation des compétences (sans fiche contrat)
create table if not exists public.competences_manuelles (
  id           bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions (id) on delete cascade,
  eleve_id     bigint not null references public.eleves (id) on delete cascade,
  competence   text not null check (length(competence) <= 20),
  niveau       text not null check (niveau in ('A', 'EVA', 'NA')),
  date_eval    date,
  lieu         text not null default 'Entreprise' check (length(lieu) <= 120),
  commentaire  text not null default '' check (length(commentaire) <= 2000),
  auteur       uuid default auth.uid(),
  maj_le       timestamptz not null default now(),
  constraint competences_manuelles_unique unique (eleve_id, competence)
);
create index if not exists competences_manuelles_promo on public.competences_manuelles (promotion_id);
alter table public.competences_manuelles enable row level security;
drop policy if exists lecture on public.competences_manuelles;
create policy lecture on public.competences_manuelles for select to authenticated using (public.est_actif());
drop policy if exists ecriture on public.competences_manuelles;
create policy ecriture on public.competences_manuelles for all to authenticated using (public.est_redacteur()) with check (public.est_redacteur());
revoke all on public.competences_manuelles from anon;
grant select, insert, update, delete on public.competences_manuelles to authenticated;

-- 3. espace élève : ses compétences évaluées sans fiche contrat (niveau, date, lieu ; pas le commentaire)
create or replace function public.eleve_competences_manuelles(jeton text) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint;
begin
  e := public.eleve_de_session(jeton);
  return (select coalesce(json_agg(json_build_object('competence', m.competence, 'niveau', m.niveau, 'date_eval', m.date_eval, 'lieu', m.lieu)), '[]')
          from competences_manuelles m where m.eleve_id = e);
end $$;
revoke all on function public.eleve_competences_manuelles(text) from public;
grant execute on function public.eleve_competences_manuelles(text) to anon, authenticated;

-- aperçu enseignant (élève fictif) : rien
create or replace function public.apercu_competences_manuelles(p bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.est_redacteur() then raise exception 'Réservé aux enseignants.'; end if;
  return '[]'::json;
end $$;
revoke all on function public.apercu_competences_manuelles(bigint) from public, anon;
grant execute on function public.apercu_competences_manuelles(bigint) to authenticated;

-- 4. sauvegarde complète : la nouvelle table en fait partie
create or replace function public.tables_sauvegarde() returns text[] language sql immutable as $$
  select array['activites', 'taches', 'competences', 'savoirs', 'durees', 'matieres', 'enseignants', 'promotions', 'eleves',
               'sequences', 'seances', 'progression_semaines', 'progression_jours', 'progression_cases', 'couverture',
               'fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes', 'commentaires', 'evaluations', 'resultats', 'appreciations',
               'cours', 'cours_partages', 'ressources_reglages', 'biblio_themes', 'biblio_livres', 'biblio_partages',
               'comptes_eleves', 'publications_eleves', 'qcm', 'qcm_partages', 'qcm_dossiers_partages', 'qcm_sessions', 'qcm_reponses',
               'seances_realisees', 'competences_manuelles'];
$$;
