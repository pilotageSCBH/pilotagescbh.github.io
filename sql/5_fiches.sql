create table if not exists public.fiches_sequence (
  sequence_id bigint primary key references public.sequences (id) on delete cascade,
  activites   text not null default '',          -- activités et tâches du référentiel visées
  situation   text not null default '',          -- situation professionnelle / support
  prerequis   text not null default '',
  modalites   text not null default '',          -- modalités d'évaluation
  ressources  text not null default '',
  bilan       text not null default '',
  maj_le      timestamptz not null default now(),
  maj_par     uuid default auth.uid()
);
create table if not exists public.fiches_seance (
  seance_id       bigint primary key references public.seances (id) on delete cascade,
  salle           text not null default '',
  prerequis       text not null default '',
  materiel        text not null default '',
  phases          jsonb not null default '[]',   -- [{phase, activite, enseignant, eleves, duree}, …]
  evaluation      text not null default '',
  differenciation text not null default '',
  bilan           text not null default '',
  maj_le          timestamptz not null default now(),
  maj_par         uuid default auth.uid()
);
create table if not exists public.contrats (
  id           bigint generated by default as identity primary key,
  type         text not null check (type in ('sommatif', 'formatif')),
  sequence_id  bigint references public.sequences (id) on delete cascade,
  seance_id    bigint references public.seances (id) on delete cascade,
  date_eval    date,
  forme        text not null default '',
  lieu         text not null default '',
  organisation text not null default '',
  duree        text not null default '',
  maj_le       timestamptz not null default now(),
  maj_par      uuid default auth.uid(),
  check ((type = 'sommatif' and sequence_id is not null) or (type = 'formatif' and seance_id is not null))
);
create unique index if not exists contrats_sommatif on public.contrats (sequence_id) where type = 'sommatif';
create unique index if not exists contrats_formatif on public.contrats (seance_id) where type = 'formatif';
create table if not exists public.criteres (
  id           bigint generated by default as identity primary key,
  contrat_id   bigint not null references public.contrats (id) on delete cascade,
  groupe       text not null,                    -- code compétence (sommatif) ou objectif opérationnel (formatif)
  groupe_ordre int  not null default 0,
  ordre        int  not null default 0,
  texte        text not null default '',
  coefficient  numeric not null default 1,
  libre        boolean not null default false,   -- ajouté par l'enseignant (sinon repris du référentiel)
  actif        boolean not null default true     -- false = critère retiré (repris du référentiel)
);
create index if not exists criteres_contrat on public.criteres (contrat_id);
create table if not exists public.notes (
  critere_id bigint not null references public.criteres (id) on delete cascade,
  eleve_id   bigint not null references public.eleves (id) on delete cascade,
  valeur     text   not null check (valeur in ('0', '1', '2', '3', '4', '5', 'NE')),
  primary key (critere_id, eleve_id)
);
