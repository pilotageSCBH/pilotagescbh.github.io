-- ----------------------------------------------------------------------------------------------- droits
create or replace function public.peut_seance(x bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.peut_sequence((select sequence_id from seances where id = x));
$$;
create or replace function public.peut_contrat(c bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select case when type = 'sommatif' then public.peut_sequence(sequence_id) else public.peut_seance(seance_id) end
                   from contrats where id = c), false);
$$;
create or replace function public.peut_critere(k bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.peut_contrat((select contrat_id from criteres where id = k));
$$;

do $$ declare t text; begin
  foreach t in array array['fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists lecture on public.%I', t);
    execute format('drop policy if exists ecriture on public.%I', t);
    execute format('create policy lecture on public.%I for select to authenticated using (public.est_actif())', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;
create policy ecriture on public.fiches_sequence for all to authenticated using (public.peut_sequence(sequence_id)) with check (public.peut_sequence(sequence_id));
create policy ecriture on public.fiches_seance for all to authenticated using (public.peut_seance(seance_id)) with check (public.peut_seance(seance_id));
create policy ecriture on public.contrats for all to authenticated
  using (case when type = 'sommatif' then public.peut_sequence(sequence_id) else public.peut_seance(seance_id) end)
  with check (case when type = 'sommatif' then public.peut_sequence(sequence_id) else public.peut_seance(seance_id) end);
create policy ecriture on public.criteres for all to authenticated using (public.peut_contrat(contrat_id)) with check (public.peut_contrat(contrat_id));
create policy ecriture on public.notes for all to authenticated using (public.peut_critere(critere_id)) with check (public.peut_critere(critere_id));

-- ----------------------------------------------------------------------------------------------- contrats : création et mise à jour depuis le référentiel
-- contrat sommatif de la séquence s : une rubrique par compétence développée dans ses séances (ordre du référentiel),
-- critères = indicateurs de performance ; relancé, ajoute seulement les compétences apparues depuis
create or replace function public.contrat_sommatif(s bigint) returns bigint
language plpgsql as $$
declare c bigint; k record; g int;
begin
  if not public.peut_sequence(s) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  select id into c from contrats where type = 'sommatif' and sequence_id = s;
  if c is null then
    insert into contrats (type, sequence_id) values ('sommatif', s) returning id into c;
  end if;
  for k in
    select cp.code, cp.indicateurs, cp.ordre from competences cp
    where cp.code in (select unnest(x.competences) from seances x where x.sequence_id = s)
      and not exists (select 1 from criteres cr where cr.contrat_id = c and cr.groupe = cp.code)
    order by cp.ordre
  loop
    insert into criteres (contrat_id, groupe, groupe_ordre, ordre, texte)
    select c, k.code, k.ordre, i.n, i.t from unnest(k.indicateurs) with ordinality as i(t, n);
    if not found then
      insert into criteres (contrat_id, groupe, groupe_ordre, ordre, texte, libre) values (c, k.code, k.ordre, 1, '', true);
    end if;
  end loop;
  return c;
end $$;

-- contrat formatif de la séance x : une rubrique par objectif opérationnel (une ligne du séquençage),
-- critères = résultats attendus de la tâche citée [A1-T1] (sinon deux critères à rédiger)
create or replace function public.contrat_formatif(x bigint) returns bigint
language plpgsql as $$
declare c bigint; l record; t text[]; tache text; g text;
begin
  if not public.peut_seance(x) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  select id into c from contrats where type = 'formatif' and seance_id = x;
  if c is not null then return c; end if;
  insert into contrats (type, seance_id) values ('formatif', x) returning id into c;
  for l in
    select n, trim(regexp_replace(ligne, '^\s*[-•]\s*', '')) as txt
    from seances, unnest(string_to_array(replace(objectifs_ops, chr(13), ''), chr(10))) with ordinality as o(ligne, n)
    where id = x and trim(regexp_replace(ligne, '^\s*[-•]\s*', '')) <> ''
  loop
    g := l.txt;
    tache := substring(l.txt from '\[(A\d+-T\d+)\]');
    t := null;
    if tache is not null then select resultats into t from taches where taches.code = tache; end if;
    if t is not null and array_length(t, 1) > 0 then
      insert into criteres (contrat_id, groupe, groupe_ordre, ordre, texte)
      select c, g, l.n, i.n, i.r from unnest(t) with ordinality as i(r, n);
    else
      insert into criteres (contrat_id, groupe, groupe_ordre, ordre, texte, libre) values (c, g, l.n, 1, '', true), (c, g, l.n, 2, '', true);
    end if;
  end loop;
  if not exists (select 1 from criteres where contrat_id = c) then
    insert into criteres (contrat_id, groupe, groupe_ordre, ordre, texte, libre)
    values (c, 'Objectif de la séance', 1, 1, '', true), (c, 'Objectif de la séance', 1, 2, '', true);
  end if;
  return c;
end $$;

