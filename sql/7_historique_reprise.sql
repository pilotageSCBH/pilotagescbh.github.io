--   - chaque ajout, modification ou suppression (séquençages, progression, élèves, fiches, contrats, notes,
--     couvertures) est noté automatiquement : qui, quand, quoi, valeurs avant / après ;
--   - l'administrateur peut recopier dans une nouvelle promotion les séquençages, le calendrier, la progression,
--     les fiches et les contrats (sans les notes) d'une promotion précédente.
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune saisie.)
