create table if not exists public.promotions (
  id           bigint generated by default as identity primary key,
  annee_debut  int  not null unique,
  libelle      text not null
);
insert into public.promotions (annee_debut, libelle)
select a, a || '-' || (a + 2) from generate_series(2025, 2055) a
on conflict (annee_debut) do nothing;

-- élèves et séquences rattachés à une promotion (données existantes : 2026-2028)
alter table public.eleves    add column if not exists promotion_id bigint references public.promotions (id) on delete cascade;
alter table public.sequences add column if not exists promotion_id bigint references public.promotions (id) on delete cascade;
update public.eleves    set promotion_id = (select id from public.promotions where annee_debut = 2026) where promotion_id is null;
update public.sequences set promotion_id = (select id from public.promotions where annee_debut = 2026) where promotion_id is null;
alter table public.eleves    alter column promotion_id set not null;
alter table public.sequences alter column promotion_id set not null;
create index if not exists eleves_promotion on public.eleves (promotion_id);
create index if not exists sequences_promotion on public.sequences (promotion_id, matiere_id);

-- numéro de séquence unique par promotion et par matière
alter table public.sequences drop constraint if exists sequences_num;
alter table public.sequences add constraint sequences_num unique (promotion_id, matiere_id, numero) deferrable initially deferred;

-- droits : tout compte actif lit les promotions ; seul l'administrateur les modifie
alter table public.promotions enable row level security;
revoke all on public.promotions from anon;
grant select, insert, update, delete on public.promotions to authenticated;
drop policy if exists lecture on public.promotions;
drop policy if exists ecriture on public.promotions;
create policy lecture on public.promotions for select to authenticated using (public.est_actif());
create policy ecriture on public.promotions for all to authenticated using (public.est_admin()) with check (public.est_admin());

-- ajout d'une séquence : dans une promotion donnée
drop function if exists public.ajouter_sequence(bigint);
create or replace function public.ajouter_sequence(m bigint, p bigint) returns bigint
language plpgsql as $$
declare n int; s bigint;
begin
  if not public.peut_matiere(m) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  select coalesce(max(numero), 0) + 1 into n from sequences where matiere_id = m and promotion_id = p;
  if n > 10 then raise exception '10 séquences au maximum par matière.'; end if;
  insert into sequences (promotion_id, matiere_id, numero) values (p, m, n) returning id into s;
  insert into seances (sequence_id, numero) values (s, 1);
  return s;
end $$;

create or replace function public.supprimer_sequence(s bigint) returns void
language plpgsql as $$
declare m bigint; p bigint; n int;
begin
  select matiere_id, promotion_id, numero into m, p, n from sequences where id = s;
  if m is null then raise exception 'Séquence introuvable.'; end if;
  if not public.peut_matiere(m) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  delete from sequences where id = s;
  update sequences set numero = numero - 1 where matiere_id = m and promotion_id = p and numero > n;
end $$;

-- reprendre le séquençage d'une matière d'une autre promotion (la promotion cible doit être vide pour cette matière)
create or replace function public.copier_sequencage(m bigint, source bigint, cible bigint) returns int
language plpgsql as $$
declare q record; s bigint; nb int := 0;
begin
  if not public.peut_matiere(m) then raise exception 'Vous ne pouvez pas modifier cette matière.'; end if;
  if source = cible then raise exception 'Choisissez une autre promotion.'; end if;
  if exists (select 1 from sequences where matiere_id = m and promotion_id = cible) then
    raise exception 'Cette promotion a déjà des séquences dans cette matière : supprimez-les d''abord.';
  end if;
  for q in select * from sequences where matiere_id = m and promotion_id = source order by numero loop
    insert into sequences (promotion_id, matiere_id, numero, intitule, objectif)
    values (cible, m, q.numero, q.intitule, q.objectif) returning id into s;
    insert into seances (sequence_id, numero, titre, duree, objectif_inter, objectifs_ops, cours, competences, savoirs)
    select s, numero, titre, duree, objectif_inter, objectifs_ops, cours, competences, savoirs
    from seances where sequence_id = q.id;
    nb := nb + 1;
  end loop;
  if nb = 0 then raise exception 'La promotion choisie n''a aucune séquence dans cette matière.'; end if;
  return nb;
end $$;

