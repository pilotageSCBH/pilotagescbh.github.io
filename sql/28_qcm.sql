-- PILOTAGE BTS SCBH  ·  mise à jour 28 : QCM FORMATIFS
-- Chaque enseignant a ses QCM (questions à une ou plusieurs bonnes réponses, vrai/faux, explication, savoir associé),
-- partageables avec des collègues. Un QCM peut être ouvert en ligne pour une promotion entre deux dates : chaque élève
-- le fait une fois dans son espace, la correction lui est montrée à la fin ; l'enseignant voit les résultats par élève,
-- par question et par savoir, et peut les reporter dans les résultats intermédiaires.
-- Nécessite le script 27 (espace élèves).
--
-- À exécuter UNE fois dans Supabase : SQL Editor → New query → coller tout ce fichier → Run.
-- (Relancer le script ne casse rien et ne supprime aucune saisie.)
-- =====================================================================================================

create table if not exists public.qcm (
  id            bigint generated by default as identity primary key,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  titre         text not null default '' check (length(titre) <= 300),
  consigne      text not null default '' check (length(consigne) <= 2000),
  matiere_id    bigint references public.matieres (id) on delete set null,
  livre_id      bigint references public.biblio_livres (id) on delete set null,     -- document de « Mes cours » d'origine
  seance_id     bigint references public.seances (id) on delete set null,           -- séance d'origine
  questions     jsonb not null default '[]' check (jsonb_typeof(questions) = 'array' and jsonb_array_length(questions) <= 200 and length(questions::text) <= 400000),
  partage_tous  boolean not null default false,
  cree_le       timestamptz not null default now(),
  maj_le        timestamptz not null default now()
);
create index if not exists qcm_prop on public.qcm (proprietaire);
create table if not exists public.qcm_partages (
  qcm_id        bigint not null references public.qcm (id) on delete cascade,
  destinataire  uuid not null references public.profils (id) on delete cascade,
  primary key (qcm_id, destinataire)
);
-- QCM ouvert en ligne pour une promotion
create table if not exists public.qcm_sessions (
  id            bigint generated by default as identity primary key,
  qcm_id        bigint not null references public.qcm (id) on delete cascade,
  proprietaire  uuid not null default auth.uid() references public.profils (id) on delete cascade,
  promotion_id  bigint not null references public.promotions (id) on delete cascade,
  ouverture     timestamptz not null default now(),
  fermeture     timestamptz not null,
  tentatives    integer not null default 1 check (tentatives between 1 and 20),
  melanger      boolean not null default true,
  evaluation_id bigint references public.evaluations (id) on delete set null,       -- report dans les résultats
  cree_le       timestamptz not null default now(),
  check (fermeture > ouverture)
);
create index if not exists qcm_sessions_promo on public.qcm_sessions (promotion_id);
create table if not exists public.qcm_reponses (
  id          bigint generated by default as identity primary key,
  session_id  bigint not null references public.qcm_sessions (id) on delete cascade,
  eleve_id    bigint not null references public.eleves (id) on delete cascade,
  tentative   integer not null default 1,
  reponses    jsonb not null default '{}',
  points      numeric not null default 0,
  total       integer not null default 0,
  rendu_le    timestamptz not null default now(),
  unique (session_id, eleve_id, tentative)
);

drop trigger if exists cours_maj on public.qcm;
create trigger cours_maj before update on public.qcm for each row execute function public.cours_maj();

-- droits
alter table public.qcm enable row level security;
alter table public.qcm_partages enable row level security;
alter table public.qcm_sessions enable row level security;
alter table public.qcm_reponses enable row level security;
revoke all on public.qcm, public.qcm_partages, public.qcm_sessions, public.qcm_reponses from anon;
grant select, insert, update, delete on public.qcm, public.qcm_partages, public.qcm_sessions to authenticated;
grant select on public.qcm_reponses to authenticated;

create or replace function public.qcm_visible(q bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.est_redacteur() and exists (select 1 from qcm x where x.id = q and (x.proprietaire = auth.uid() or x.partage_tous
    or exists (select 1 from qcm_partages p where p.qcm_id = x.id and p.destinataire = auth.uid())));
$$;
drop policy if exists lecture on public.qcm;
drop policy if exists ecriture on public.qcm;
create policy lecture on public.qcm for select to authenticated using (public.qcm_visible(id));
create policy ecriture on public.qcm for all to authenticated using (proprietaire = auth.uid() and public.est_redacteur()) with check (proprietaire = auth.uid() and public.est_redacteur());
drop policy if exists lecture on public.qcm_partages;
drop policy if exists ecriture on public.qcm_partages;
create policy lecture on public.qcm_partages for select to authenticated using (destinataire = auth.uid() or exists (select 1 from qcm x where x.id = qcm_id and x.proprietaire = auth.uid()));
create policy ecriture on public.qcm_partages for all to authenticated
  using (exists (select 1 from qcm x where x.id = qcm_id and x.proprietaire = auth.uid()) and public.est_redacteur())
  with check (exists (select 1 from qcm x where x.id = qcm_id and x.proprietaire = auth.uid()) and public.est_redacteur());
-- sessions et réponses : visibles de tous les enseignants (suivi de la classe) ; sessions modifiables par leur auteur
drop policy if exists lecture on public.qcm_sessions;
drop policy if exists ecriture on public.qcm_sessions;
create policy lecture on public.qcm_sessions for select to authenticated using (public.est_redacteur());
create policy ecriture on public.qcm_sessions for all to authenticated using (proprietaire = auth.uid() and public.est_redacteur())
  with check (proprietaire = auth.uid() and public.est_redacteur() and exists (select 1 from qcm x where x.id = qcm_id and public.qcm_visible(x.id)));
drop policy if exists lecture on public.qcm_reponses;
create policy lecture on public.qcm_reponses for select to authenticated using (public.est_redacteur());

-- ------------------------------------------------------------------------------------------- élève
-- QCM de sa promotion : ouverts, à venir, terminés ; ses tentatives et son score
create or replace function public.eleve_qcm_liste(jeton text) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; p bigint;
begin
  e := public.eleve_de_session(jeton);
  select promotion_id into p from eleves where id = e;
  return (select coalesce(json_agg(json_build_object('session', s.id, 'titre', q.titre, 'consigne', q.consigne, 'matiere_id', q.matiere_id,
      'ouverture', s.ouverture, 'fermeture', s.fermeture, 'tentatives', s.tentatives, 'nb_questions', jsonb_array_length(q.questions),
      'faites', (select count(*) from qcm_reponses r where r.session_id = s.id and r.eleve_id = e),
      'meilleur', (select max(case when r.total > 0 then r.points / r.total * 20 end) from qcm_reponses r where r.session_id = s.id and r.eleve_id = e))
      order by s.fermeture desc), '[]')
    from qcm_sessions s join qcm q on q.id = s.qcm_id where s.promotion_id = p and s.ouverture <= now() + interval '14 days');
end $$;
-- questions sans les bonnes réponses (QCM ouvert, tentatives restantes)
create or replace function public.eleve_qcm_ouvrir(jeton text, session bigint) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; s record; q record;
begin
  e := public.eleve_de_session(jeton);
  select * into s from qcm_sessions where id = session and promotion_id = (select promotion_id from eleves where id = e);
  if not found then raise exception 'QCM introuvable.'; end if;
  if now() < s.ouverture then raise exception 'Ce QCM n’est pas encore ouvert.'; end if;
  if now() > s.fermeture then raise exception 'Ce QCM est fermé.'; end if;
  if (select count(*) from qcm_reponses where session_id = s.id and eleve_id = e) >= s.tentatives then raise exception 'Vous avez déjà fait ce QCM.'; end if;
  select * into q from qcm where id = s.qcm_id;
  return json_build_object('session', s.id, 'titre', q.titre, 'consigne', q.consigne, 'melanger', s.melanger, 'fermeture', s.fermeture,
    'questions', (select coalesce(json_agg(json_build_object('id', x ->> 'id', 'type', x ->> 'type', 'texte', x ->> 'texte',
      'choix', (select coalesce(json_agg(json_build_object('id', c ->> 'id', 'texte', c ->> 'texte')), '[]') from jsonb_array_elements(x -> 'choix') c))), '[]')
      from jsonb_array_elements(q.questions) x));
end $$;
-- correction : 1 point par question entièrement juste (toutes les bonnes réponses, aucune fausse)
create or replace function public.qcm_noter(questions jsonb, reponses jsonb) returns numeric
language sql immutable as $$
  select coalesce(sum(case when
      (select coalesce(array_agg(c ->> 'id' order by c ->> 'id'), '{}') from jsonb_array_elements(x -> 'choix') c where (c ->> 'bon')::boolean)
      = (select coalesce(array_agg(v order by v), '{}') from jsonb_array_elements_text(coalesce(reponses -> (x ->> 'id'), '[]')) v)
    then 1 else 0 end), 0)
  from jsonb_array_elements(questions) x;
$$;
create or replace function public.eleve_qcm_rendre(jeton text, session bigint, reponses jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; s record; q record; n int; pts numeric;
begin
  e := public.eleve_de_session(jeton);
  select * into s from qcm_sessions where id = session and promotion_id = (select promotion_id from eleves where id = e);
  if not found then raise exception 'QCM introuvable.'; end if;
  if now() > s.fermeture + interval '10 minutes' then raise exception 'Ce QCM est fermé : vos réponses n’ont pas été enregistrées.'; end if;
  select count(*) into n from qcm_reponses where session_id = s.id and eleve_id = e;
  if n >= s.tentatives then raise exception 'Vous avez déjà fait ce QCM.'; end if;
  if jsonb_typeof(reponses) <> 'object' or length(reponses::text) > 50000 then raise exception 'Réponses illisibles.'; end if;
  select * into q from qcm where id = s.qcm_id;
  pts := public.qcm_noter(q.questions, reponses);
  insert into qcm_reponses (session_id, eleve_id, tentative, reponses, points, total) values (s.id, e, n + 1, reponses, pts, jsonb_array_length(q.questions));
  insert into consultations_eleves (eleve_id, quoi, titre) values (e, 'qcm', left(q.titre, 200));
  return public.eleve_qcm_correction(jeton, session);
end $$;
-- correction (après avoir rendu) : bonnes réponses, explications, réponses de l'élève (dernière tentative)
create or replace function public.eleve_qcm_correction(jeton text, session bigint) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; s record; q record; r record;
begin
  e := public.eleve_de_session(jeton);
  select * into s from qcm_sessions where id = session and promotion_id = (select promotion_id from eleves where id = e);
  if not found then raise exception 'QCM introuvable.'; end if;
  select * into r from qcm_reponses where session_id = s.id and eleve_id = e order by tentative desc limit 1;
  if not found then raise exception 'Faites d’abord le QCM.'; end if;
  select * into q from qcm where id = s.qcm_id;
  return json_build_object('session', s.id, 'titre', q.titre, 'points', r.points, 'total', r.total, 'reponses', r.reponses, 'tentative', r.tentative, 'tentatives', s.tentatives,
    'questions', (select coalesce(json_agg(json_build_object('id', x ->> 'id', 'type', x ->> 'type', 'texte', x ->> 'texte', 'explication', x ->> 'explication', 'savoir', x ->> 'savoir',
      'choix', (select coalesce(json_agg(json_build_object('id', c ->> 'id', 'texte', c ->> 'texte', 'bon', coalesce((c ->> 'bon')::boolean, false))), '[]') from jsonb_array_elements(x -> 'choix') c))), '[]')
      from jsonb_array_elements(q.questions) x));
end $$;
grant execute on function public.eleve_qcm_liste(text), public.eleve_qcm_ouvrir(text, bigint), public.eleve_qcm_rendre(text, bigint, jsonb), public.eleve_qcm_correction(text, bigint) to anon, authenticated;

-- ------------------------------------------------------------------------------------------- enseignant : report dans les résultats
-- crée (ou met à jour) un résultat intermédiaire avec la note /20 de chaque élève (meilleure tentative)
create or replace function public.qcm_reporter(session bigint, matiere bigint, libelle text, coef numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare s record; v bigint;
begin
  select * into s from qcm_sessions where id = session;
  if not found then raise exception 'QCM introuvable.'; end if;
  if not public.peut_matiere(matiere) then raise exception 'Vous ne pouvez pas saisir de résultats dans cette matière.'; end if;
  v := s.evaluation_id;
  if v is null or not exists (select 1 from evaluations where id = v) then
    insert into evaluations (promotion_id, matiere_id, libelle, date_eval, coefficient, bareme)
    values (s.promotion_id, matiere, left(libelle, 200), s.fermeture::date, coalesce(coef, 1), 20) returning id into v;
    update qcm_sessions set evaluation_id = v where id = s.id;
  else
    update evaluations set libelle = left(libelle, 200), coefficient = coalesce(coef, 1), matiere_id = matiere where id = v;
  end if;
  delete from resultats where evaluation_id = v;
  insert into resultats (evaluation_id, eleve_id, valeur)
  select v, r.eleve_id, round(max(r.points / nullif(r.total, 0) * 20), 1)::text
  from qcm_reponses r where r.session_id = s.id group by r.eleve_id;
  return v;
end $$;
grant execute on function public.qcm_reporter(bigint, bigint, text, numeric) to authenticated;

