-- contexte lisible (complété : résultats intermédiaires)
create or replace function public.contexte_ligne(t text, j jsonb, out p bigint, out m bigint, out c text)
language plpgsql stable security definer set search_path = public as $$
declare sq record; x record; k record; ct record; e record;
begin
  case t
  when 'sequences' then
    p := (j->>'promotion_id')::bigint; m := (j->>'matiere_id')::bigint;
    c := 'Séquence ' || (j->>'numero') || coalesce(' · ' || nullif(j->>'intitule', ''), '');
  when 'seances' then
    select * into sq from sequences where id = (j->>'sequence_id')::bigint;
    p := sq.promotion_id; m := sq.matiere_id;
    c := 'Séance ' || coalesce(sq.numero::text, '?') || '.' || (j->>'numero') || coalesce(' · ' || nullif(j->>'titre', ''), '');
  when 'progression_cases' then
    p := (j->>'promotion_id')::bigint; m := (j->>'matiere_id')::bigint;
    c := 'Progression · semaine ' || (j->>'semaine');
  when 'progression_semaines' then
    p := (j->>'promotion_id')::bigint; c := 'Calendrier · semaine ' || (j->>'semaine');
  when 'progression_jours' then
    p := (j->>'promotion_id')::bigint; c := 'Évènement · jour ' || (j->>'jour');
  when 'eleves' then
    p := (j->>'promotion_id')::bigint; c := 'Élève ' || (j->>'nom') || ' ' || (j->>'prenom');
  when 'couverture' then
    p := (j->>'promotion_id')::bigint; m := (j->>'matiere_id')::bigint;
    c := 'Couverture ' || case when j->>'type' = 'savoir' then 'savoir ' else 'compétence ' end || (j->>'code');
  when 'fiches_sequence' then
    select * into sq from sequences where id = (j->>'sequence_id')::bigint;
    p := sq.promotion_id; m := sq.matiere_id; c := 'Fiche de préparation · séquence ' || coalesce(sq.numero::text, '?');
  when 'fiches_seance' then
    select x2.numero, s2.numero as sn, s2.promotion_id, s2.matiere_id into x from seances x2 join sequences s2 on s2.id = x2.sequence_id where x2.id = (j->>'seance_id')::bigint;
    p := x.promotion_id; m := x.matiere_id; c := 'Fiche de déroulement · séance ' || coalesce(x.sn || '.' || x.numero, '?');
  when 'contrats', 'criteres', 'notes' then
    if t = 'notes' then
      select * into k from criteres where id = (j->>'critere_id')::bigint;
      select * into ct from contrats where id = k.contrat_id;
      select * into e from eleves where id = (j->>'eleve_id')::bigint;
    elsif t = 'criteres' then
      select * into ct from contrats where id = (j->>'contrat_id')::bigint;
    else
      select * into ct from contrats where id = (j->>'id')::bigint;
      if ct.id is null then ct := jsonb_populate_record(null::contrats, j); end if;
    end if;
    if ct.type = 'sommatif' then
      select * into sq from sequences where id = ct.sequence_id;
      p := sq.promotion_id; m := sq.matiere_id; c := 'Contrat sommatif · séquence ' || coalesce(sq.numero::text, '?');
    elsif ct.type = 'formatif' then
      select x2.numero, s2.numero as sn, s2.promotion_id, s2.matiere_id into x from seances x2 join sequences s2 on s2.id = x2.sequence_id where x2.id = ct.seance_id;
      p := x.promotion_id; m := x.matiere_id; c := 'Contrat formatif · séance ' || coalesce(x.sn || '.' || x.numero, '?');
    else c := 'Contrat';
    end if;
    if t = 'criteres' then c := c || ' · critère « ' || left(coalesce(j->>'texte', ''), 60) || ' »'; end if;
    if t = 'notes' then c := c || ' · note de ' || coalesce(e.nom || ' ' || e.prenom, 'élève'); end if;
  when 'evaluations' then
    p := (j->>'promotion_id')::bigint; m := (j->>'matiere_id')::bigint;
    c := 'Résultat intermédiaire · ' || coalesce(nullif(j->>'libelle', ''), 'sans titre');
  when 'resultats' then
    select * into x from evaluations where id = (j->>'evaluation_id')::bigint;
    select * into e from eleves where id = (j->>'eleve_id')::bigint;
    p := x.promotion_id; m := x.matiere_id;
    c := 'Résultat intermédiaire · ' || coalesce(nullif(x.libelle, ''), 'sans titre') || ' · note de ' || coalesce(e.nom || ' ' || e.prenom, 'élève');
  else c := t;
  end case;
end $$;

create or replace function public.noter_journal() returns trigger
language plpgsql security definer set search_path = public as $$
declare a jsonb; n jsonb; ch text[]; ctx record; qui_n text;
        ann boolean := coalesce(current_setting('pilotage.annulation', true), '') = 'on';
begin
  if tg_op <> 'INSERT' then a := to_jsonb(old) - 'maj_le' - 'maj_par'; end if;
  if tg_op <> 'DELETE' then n := to_jsonb(new) - 'maj_le' - 'maj_par'; end if;
  if tg_op = 'UPDATE' then
    select coalesce(array_agg(k), '{}') into ch from jsonb_object_keys(n) k where n->k is distinct from a->k;
    if cardinality(ch) = 0 then return null; end if;
  end if;
  select * into ctx from public.contexte_ligne(tg_table_name, coalesce(n, a));
  select coalesce(nullif(profils.nom, ''), profils.email) into qui_n from profils where id = auth.uid();
  insert into journal (qui_nom, table_nom, action, promotion_id, matiere_id, contexte, champs, avant, apres, annulation)
  values (coalesce(qui_n, ''), tg_table_name, case tg_op when 'INSERT' then 'ajout' when 'UPDATE' then 'modification' else 'suppression' end,
          ctx.p, ctx.m, case when ann then 'Annulation · ' else '' end || ctx.c, coalesce(ch, '{}'), a, n, ann);
  return null;
end $$;

do $$ declare t text; begin
  foreach t in array array['sequences', 'seances', 'progression_cases', 'progression_semaines', 'progression_jours', 'eleves',
                           'couverture', 'fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes', 'evaluations', 'resultats'] loop
    execute format('drop trigger if exists journal on public.%I', t);
    execute format('create trigger journal after insert or update or delete on public.%I for each row execute function public.noter_journal()', t);
  end loop;
end $$;

-- colonnes de la clé primaire d'une table
create or replace function public.cles_primaires(t text) returns text[]
language sql stable set search_path = public as $$
  select array_agg(a.attname::text order by array_position(i.indkey::int2[], a.attnum))
  from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
  where i.indrelid = ('public.' || quote_ident(t))::regclass and i.indisprimary;
$$;

-- Annule la dernière action (une même opération = une transaction) de l'utilisateur connecté dans la promotion,
-- parmi les tables de la page. Une valeur modifiée depuis par un collègue n'est pas écrasée.
create or replace function public.annuler(promo bigint, tables text[]) returns json
language plpgsql security definer set search_path = public as $$
declare t bigint; c text; e record; cle text[]; cols text; cond text; nb int := 0;
        ordre text[] := array['eleves', 'evaluations', 'sequences', 'seances', 'couverture', 'progression_semaines', 'progression_jours',
                              'progression_cases', 'fiches_sequence', 'fiches_seance', 'contrats', 'criteres', 'notes', 'resultats'];
begin
  if not public.est_redacteur() then raise exception 'Votre compte ne permet pas de modifier.'; end if;
  select j.tx, j.contexte into t, c from journal j
  where j.qui = auth.uid() and j.promotion_id = promo and j.table_nom = any (tables) and not j.annule and not j.annulation
  order by j.id desc limit 1;
  if t is null then return null; end if;
  perform set_config('pilotage.annulation', 'on', true);
  set constraints all deferred;
  -- 1) remettre les lignes supprimées (les « parents » d'abord)
  for e in select * from journal where tx = t and qui = auth.uid() and not annule and not annulation and action = 'suppression'
           order by array_position(ordre, table_nom), id loop
    select string_agg(quote_ident(k), ', ') into cols from jsonb_object_keys(e.avant) k
    where exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = e.table_nom and column_name = k);
    execute format('insert into public.%1$I (%2$s) select %2$s from jsonb_populate_record(null::public.%1$I, $1) on conflict (%3$s) do nothing',
                   e.table_nom, cols, (select string_agg(quote_ident(k), ', ') from unnest(public.cles_primaires(e.table_nom)) k)) using e.avant;
    nb := nb + 1;
  end loop;
  -- 2) défaire les ajouts et les modifications, de la plus récente à la plus ancienne
  for e in select * from journal where tx = t and qui = auth.uid() and not annule and not annulation and action <> 'suppression'
           order by id desc loop
    cle := public.cles_primaires(e.table_nom);
    select string_agg(format('x.%1$I = r.%1$I', k), ' and ') into cond from unnest(cle) k;
    if e.action = 'ajout' then
      execute format('delete from public.%1$I x using jsonb_populate_record(null::public.%1$I, $1) r where %2$s', e.table_nom, cond) using e.apres;
    else
      execute format('update public.%1$I x set %2$s from jsonb_populate_record(null::public.%1$I, $1) r where %3$s '
                     'and not exists (select 1 from unnest($3::text[]) k where to_jsonb(x)->k is distinct from $2->k)',
                     e.table_nom, (select string_agg(format('%1$I = r.%1$I', k), ', ') from unnest(e.champs) k), cond)
      using e.avant, e.apres, e.champs;
    end if;
    nb := nb + 1;
  end loop;
  update journal set annule = true where tx = t and qui = auth.uid() and not annulation;
  return json_build_object('contexte', c, 'nb', nb);
end $$;

