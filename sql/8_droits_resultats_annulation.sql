-- compte actif qui a le droit de modifier (tout sauf « lecture »)
create or replace function public.est_redacteur() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profils where id = auth.uid() and actif and role <> 'lecture');
$$;
-- peut modifier la matière m : administrateur, ou enseignant de cette matière (jamais un compte « lecture »)
create or replace function public.peut_matiere(m bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.est_admin() or exists (
    select 1 from enseignants e join profils p on p.id = e.profil_id
    where p.id = auth.uid() and p.actif and p.role <> 'lecture' and m = any (e.matieres));
$$;
-- calendrier commun : tous les comptes qui peuvent modifier
drop policy if exists ecriture on public.progression_semaines;
drop policy if exists ecriture on public.progression_jours;
create policy ecriture on public.progression_semaines for all to authenticated using (public.est_redacteur()) with check (public.est_redacteur());
create policy ecriture on public.progression_jours for all to authenticated using (public.est_redacteur()) with check (public.est_redacteur());

-- ----------------------------------------------------------------------------------------------- commentaires
create table if not exists public.commentaires (
  id           bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions (id) on delete cascade,
  seance_id    bigint not null references public.seances (id) on delete cascade,
  auteur       uuid not null default auth.uid() references public.profils (id) on delete cascade,
  auteur_nom   text not null default '',
  texte        text not null default '',
  prive        boolean not null default false,          -- true : visible par son auteur seul
  cree_le      timestamptz not null default now(),
  maj_le       timestamptz not null default now()
);
create index if not exists commentaires_promo on public.commentaires (promotion_id);
alter table public.commentaires enable row level security;
revoke all on public.commentaires from anon;
grant select, insert, update, delete on public.commentaires to authenticated;
drop policy if exists lecture on public.commentaires;
drop policy if exists ajout on public.commentaires;
drop policy if exists modif on public.commentaires;
drop policy if exists suppr on public.commentaires;
create policy lecture on public.commentaires for select to authenticated using (public.est_actif() and (not prive or auteur = auth.uid()));
create policy ajout on public.commentaires for insert to authenticated with check (public.est_redacteur() and auteur = auth.uid());
create policy modif on public.commentaires for update to authenticated using (auteur = auth.uid() and public.est_redacteur()) with check (auteur = auth.uid());
create policy suppr on public.commentaires for delete to authenticated using ((auteur = auth.uid() and public.est_redacteur()) or (public.est_admin() and not prive));
create or replace function public.trace_commentaire() returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.maj_le := now();
  if tg_op = 'INSERT' then
    select coalesce(nullif(nom, ''), email) into new.auteur_nom from profils where id = auth.uid();
  end if;
  return new;
end $$;
drop trigger if exists trace on public.commentaires;
create trigger trace before insert or update on public.commentaires for each row execute function public.trace_commentaire();

