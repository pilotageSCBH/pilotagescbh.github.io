-- =====================================================================================================
-- 39 · Stages et entreprises · Épreuves et CCF · Annonces aux élèves
-- À exécuter après le script 38. Peut être exécuté plusieurs fois sans risque.
-- Aucune donnée d'élève dans ce script (seulement la structure).
-- Les stages (entreprises, tuteurs, visites) ne sont visibles que des enseignants.
-- Les élèves voient seulement : les épreuves de leur promotion (dates, compétences) et les annonces en cours.
-- =====================================================================================================

-- 1. stages, PFMP, apprentissage : une période en entreprise par ligne
create table if not exists public.stages (
  id               bigint generated by default as identity primary key,
  promotion_id     bigint not null references public.promotions (id) on delete cascade,
  eleve_id         bigint not null references public.eleves (id) on delete cascade,
  type             text not null default 'Stage' check (type in ('Stage', 'PFMP', 'Apprentissage', 'Autre')),
  entreprise       text not null default '' check (length(entreprise) <= 200),
  adresse          text not null default '' check (length(adresse) <= 300),
  commune          text not null default '' check (length(commune) <= 120),
  entreprise_tel   text not null default '' check (length(entreprise_tel) <= 40),
  entreprise_mail  text not null default '' check (length(entreprise_mail) <= 160),
  tuteur           text not null default '' check (length(tuteur) <= 160),
  tuteur_fonction  text not null default '' check (length(tuteur_fonction) <= 120),
  tuteur_tel       text not null default '' check (length(tuteur_tel) <= 40),
  tuteur_mail      text not null default '' check (length(tuteur_mail) <= 160),
  date_debut       date,
  date_fin         date,
  referent         uuid,                                      -- enseignant référent (profil)
  convention       text not null default 'À faire' check (convention in ('À faire', 'Envoyée', 'Signée', 'Sans objet')),
  attestation      boolean not null default false,            -- certificat / attestation de stage reçu
  notes            text not null default '' check (length(notes) <= 4000),
  maj_le           timestamptz not null default now()
);
create index if not exists stages_promo on public.stages (promotion_id);
create table if not exists public.visites (
  id             bigint generated by default as identity primary key,
  stage_id       bigint not null references public.stages (id) on delete cascade,
  date_visite    date,
  mode           text not null default 'Sur place' check (mode in ('Sur place', 'Téléphone', 'Visio')),
  par            uuid default auth.uid(),
  compte_rendu   text not null default '' check (length(compte_rendu) <= 6000),
  maj_le         timestamptz not null default now()
);
create index if not exists visites_stage on public.visites (stage_id);

-- 2. épreuves de l'examen (une ligne par épreuve ou sous-épreuve) et leurs situations datées
create table if not exists public.epreuves (
  id            bigint generated by default as identity primary key,
  promotion_id  bigint not null references public.promotions (id) on delete cascade,
  code          text not null default '' check (length(code) <= 20),        -- ex. E51
  unite         text not null default '' check (length(unite) <= 20),       -- ex. U51
  intitule      text not null default '' check (length(intitule) <= 200),
  coefficient   numeric,
  forme         text not null default '' check (length(forme) <= 120),      -- ex. CCF · 2 situations
  duree         text not null default '' check (length(duree) <= 60),
  competences   text[] not null default '{}',
  situations    jsonb not null default '[]',                                 -- [{ "libelle", "debut", "fin", "lieu", "note" }]
  facultative   boolean not null default false,
  ordre         int not null default 0,
  notes         text not null default '' check (length(notes) <= 4000),
  maj_le        timestamptz not null default now()
);
create index if not exists epreuves_promo on public.epreuves (promotion_id, ordre);

-- 3. annonces aux élèves d'une promotion
create table if not exists public.annonces (
  id            bigint generated by default as identity primary key,
  promotion_id  bigint not null references public.promotions (id) on delete cascade,
  auteur        uuid default auth.uid(),
  titre         text not null default '' check (length(titre) <= 160),
  texte         text not null default '' check (length(texte) <= 3000),
  importante    boolean not null default false,
  debut         date not null default current_date,
  fin           date,
  cree_le       timestamptz not null default now()
);
create index if not exists annonces_promo on public.annonces (promotion_id, debut);

-- droits : lecture par les comptes actifs, écriture par les enseignants (rédacteurs)
do $$ declare t text; begin
  foreach t in array array['stages', 'visites', 'epreuves', 'annonces'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists lecture on public.%I', t);
    execute format('create policy lecture on public.%I for select to authenticated using (public.est_actif())', t);
    execute format('drop policy if exists ecriture on public.%I', t);
    execute format('create policy ecriture on public.%I for all to authenticated using (public.est_redacteur()) with check (public.est_redacteur())', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- 4. espace élève : épreuves de sa promotion (sans les notes internes) et annonces en cours
create or replace function public.epreuves_promo(p bigint) returns json
language sql stable security definer set search_path = public as $$
  select coalesce(json_agg(json_build_object('id', x.id, 'code', x.code, 'unite', x.unite, 'intitule', x.intitule, 'coefficient', x.coefficient,
    'forme', x.forme, 'duree', x.duree, 'competences', x.competences, 'situations', x.situations, 'facultative', x.facultative) order by x.ordre, x.id), '[]')
  from epreuves x where x.promotion_id = p;
$$;
revoke all on function public.epreuves_promo(bigint) from public, anon, authenticated;
create or replace function public.annonces_promo(p bigint) returns json
language sql stable security definer set search_path = public as $$
  select coalesce(json_agg(json_build_object('id', a.id, 'titre', a.titre, 'texte', a.texte, 'importante', a.importante, 'debut', a.debut, 'fin', a.fin,
    'auteur', coalesce(nullif((select e.nom from enseignants e where e.profil_id = a.auteur order by e.id limit 1), ''), (select nullif(pr.nom, '') from profils pr where pr.id = a.auteur), ''))
    order by a.importante desc, a.debut desc, a.id desc), '[]')
  from annonces a where a.promotion_id = p and a.debut <= current_date and (a.fin is null or a.fin >= current_date);
$$;
revoke all on function public.annonces_promo(bigint) from public, anon, authenticated;

create or replace function public.eleve_epreuves(jeton text) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; p bigint;
begin
  e := public.eleve_de_session(jeton);
  select promotion_id into p from eleves where id = e;
  return public.epreuves_promo(p);
end $$;
create or replace function public.eleve_annonces(jeton text) returns json
language plpgsql security definer set search_path = public as $$
declare e bigint; p bigint;
begin
  e := public.eleve_de_session(jeton);
  select promotion_id into p from eleves where id = e;
  return public.annonces_promo(p);
end $$;
revoke all on function public.eleve_epreuves(text), public.eleve_annonces(text) from public;
grant execute on function public.eleve_epreuves(text), public.eleve_annonces(text) to anon, authenticated;

create or replace function public.apercu_epreuves(p bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.est_redacteur() then raise exception 'Réservé aux enseignants.'; end if;
  return public.epreuves_promo(p);
end $$;
create or replace function public.apercu_annonces(p bigint) returns json
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.est_redacteur() then raise exception 'Réservé aux enseignants.'; end if;
  return public.annonces_promo(p);
end $$;
revoke all on function public.apercu_epreuves(bigint), public.apercu_annonces(bigint) from public, anon;
grant execute on function public.apercu_epreuves(bigint), public.apercu_annonces(bigint) to authenticated;

